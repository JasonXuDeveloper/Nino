//
// It writes units UTF-16 code units (little-endian) at src as WTF-8 at dst (room for 3*units+64 bytes) and returns
// the bytes written. Each block of 16 units is widened to 16 lanes of 32 bits, each lane given the code point c
// (of the pair, for a high surrogate followed by a low one) and its UTF-8 in full 4-byte form, shifted down to its
// length (0 for the low surrogate of a pair), and the bytes kept compressed to the front.
