// Command wiregen writes strings_wire_amd64.s, the string writer's vector paths (see strings_wire_amd64.go):
//
//	go run ./internal/wiregen -out strings_wire_amd64.s
//
// The kernels are written once here and placed in each function that takes them, with its own label prefix: Go's
// assembler has no macros that could hold labels.
package main

import (
	"flag"
	"fmt"
	"log"
	"os"
	"strings"
)

func main() {
	out := flag.String("out", "strings_wire_amd64.s", "the file to write")
	flag.Parse()
	var b strings.Builder
	b.WriteString(header)
	b.WriteString(constants())
	b.WriteString(single("wireStringAVX2", setupAVX2, kernelAVX2, "s"))
	b.WriteString(many("wireStringsAVX2", setupAVX2, kernelAVX2, "m"))
	b.WriteString(single("wireStringAVX512", setupAVX512, kernelAVX512, "t"))
	b.WriteString(many("wireStringsAVX512", setupAVX512, kernelAVX512, "n"))
	b.WriteString(readers)
	b.WriteString(cpu)
	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
}

// sub replaces each {key} in s with its value (pairs of key and value).
func sub(s string, kv ...string) string {
	for i := 0; i < len(kv); i += 2 {
		s = strings.ReplaceAll(s, "{"+kv[i]+"}", kv[i+1])
	}
	return s
}

// replaceOnce replaces old, which must occur in s exactly once.
func replaceOnce(s, old, new string) string {
	if strings.Count(s, old) != 1 {
		log.Fatalf("wiregen: %q occurs %d times", old, strings.Count(s, old))
	}
	return strings.Replace(s, old, new, 1)
}

// replaceSpan replaces the text from the first from (at or after the first after) up to and including the first to
// after it.
func replaceSpan(s, after, from, to, new string) string {
	a := strings.Index(s, after)
	if a < 0 {
		log.Fatalf("wiregen: no %q", after)
	}
	i := strings.Index(s[a:], from)
	if i < 0 {
		log.Fatalf("wiregen: no %q", from)
	}
	i += a
	j := strings.Index(s[i:], to)
	if j < 0 {
		log.Fatalf("wiregen: no %q", to)
	}
	return s[:i] + new + s[i+j+len(to):]
}

const header = `//go:build !purego

#include "textflag.h"

// Code generated by internal/wiregen; DO NOT EDIT. (See strings_wire_amd64.go.)

`

// constant is a 32-byte constant (or more) in the wire<> table, under the name K_<name>.
type constant struct {
	name, comment string
	bytes         []byte
}

func fill(b byte) []byte { return []byte(strings.Repeat(string([]byte{b}), 32)) }

// lanes is a 16-byte table in both lanes.
func lanes(t [16]byte) []byte { return append(t[:], t[:]...) }

// The checks of the UTF-8 validation (Keiser and Lemire, "Validating UTF-8 in less than one instruction per byte"),
// without the one for surrogates: the text is WTF-8, and a surrogate is one UTF-16 code unit like any other char.
const (
	tooShort     = 1 << 0
	tooLong      = 1 << 1
	overlong3    = 1 << 2
	tooLarge     = 1 << 3
	overlong2    = 1 << 5
	tooLarge1000 = 1 << 6
	overlong4    = 1 << 6
	twoConts     = 1 << 7
	carry        = tooShort | tooLong | twoConts
)

func constants() string {
	var t1, t2, t3 [16]byte
	for i := range t1 {
		switch {
		case i < 8:
			t1[i] = tooLong
		case i < 12:
			t1[i] = twoConts
		case i == 12:
			t1[i] = tooShort | overlong2
		case i == 13:
			t1[i] = tooShort
		case i == 14:
			t1[i] = tooShort | overlong3
		default:
			t1[i] = tooShort | tooLarge | tooLarge1000 | overlong4
		}
		switch {
		case i == 0:
			t2[i] = carry | overlong3 | overlong2 | overlong4
		case i == 1:
			t2[i] = carry | overlong2
		case i < 4:
			t2[i] = carry
		case i == 4:
			t2[i] = carry | tooLarge
		default:
			t2[i] = carry | tooLarge | tooLarge1000
		}
		switch {
		case i < 8 || i >= 12:
			t3[i] = tooShort
		case i == 8:
			t3[i] = tooLong | overlong2 | twoConts | overlong3 | tooLarge1000 | overlong4
		case i == 9:
			t3[i] = tooLong | overlong2 | twoConts | overlong3 | tooLarge
		default:
			t3[i] = tooLong | overlong2 | twoConts | tooLarge
		}
	}
	tail := fill(0xFF)
	tail[29], tail[30], tail[31] = 0xEF, 0xDF, 0xBF
	mask := append(fill(0xFF), make([]byte, 32)...)
	table := []constant{
		{"C0", "C0 (a continuation is less, signed)", fill(0xC0)},
		{"NIB", "low nibble", fill(0x0F)},
		{"S60", "E0 - 80", fill(0x60)},
		{"S70", "F0 - 80", fill(0x70)},
		{"B80", "80", fill(0x80)},
		{"C3", "C3", fill(0xC3)},
		{"B40", "40", fill(0x40)},
		{"FE", "FE", fill(0xFE)},
		{"C2", "C2", fill(0xC2)},
		{"E0", "E0", fill(0xE0)},
		{"F0", "F0", fill(0xF0)},
		{"F8", "F8", fill(0xF8)},
		{"B3F", "3F", fill(0x3F)},
		{"B07", "07", fill(0x07)},
		{"B03", "03", fill(0x03)},
		{"D8", "D8", fill(0xD8)},
		{"DC", "DC", fill(0xDC)},
		{"TAIL", "the most each of the last three bytes may be (no char cut at the end)", tail},
		{"T1", "checks by the high nibble of the byte before", lanes(t1)},
		{"T2", "by its low nibble", lanes(t2)},
		{"T3", "by the high nibble of the byte", lanes(t3)},
		{"MASK", "32 bytes of FF then 32 of 0: read from 32 minus the bytes left on, a mask of the bytes of the text", mask},
	}
	var b, defs strings.Builder
	at := 0
	for _, c := range table {
		fmt.Fprintf(&b, "// %#x: %s\n", at, c.comment)
		for i := 0; i < len(c.bytes); i += 8 {
			var v uint64
			for k := 7; k >= 0; k-- {
				v = v<<8 | uint64(c.bytes[i+k])
			}
			fmt.Fprintf(&b, "DATA wire<>+%#x(SB)/8, $%#016x\n", at+i, v)
		}
		fmt.Fprintf(&defs, "#define K_%s wire<>+%#x(SB)\n", c.name, at)
		at += len(c.bytes)
	}
	fmt.Fprintf(&b, "GLOBL wire<>(SB), RODATA|NOPTR, $%#x\n\n", at)
	return b.String() + defs.String() + "\n"
}

// load32 reads the block at DX into Y0 (R13 the mask of its bytes), then jumps to {p}{body}.
func load32(p, l, body string) string {
	return sub(`	MOVL    $0xffffffff, R13
	CMPQ    AX, $32
	JB      {p}{l}tail
	VMOVDQU (SI)(DX*1), Y0
	JMP     {p}{body}

{p}{l}tail:
	// Fewer than 32 bytes left: R13 the mask of those, the bytes past them zeros.
	MOVL    $1, R13
	MOVQ    AX, CX
	SHLL    CX, R13
	DECL    R13
	LEAQ    (SI)(DX*1), R8
	MOVL    R8, R9
	ANDL    $4095, R9
	CMPL    R9, $4064
	JA      {p}{l}copy
	VMOVDQU (R8), Y0
	LEAQ    K_MASK, R10
	ADDQ    $32, R10
	SUBQ    AX, R10
	VPAND   (R10), Y0, Y0
	JMP     {p}{body}

{p}{l}copy:
	// The 32 bytes from there cross into the next page: the bytes left are copied to where the output goes next
	// (room not written yet), then read from there.
	VPXOR   Y0, Y0, Y0
	VMOVDQU Y0, (DI)
	XORQ    R9, R9

{p}{l}byte:
	MOVBLZX (R8)(R9*1), R10
	MOVB    R10, (DI)(R9*1)
	INCQ    R9
	CMPQ    R9, AX
	JB      {p}{l}byte
	VMOVDQU (DI), Y0
	JMP     {p}{body}
`, "p", p, "l", l, "body", body)
}

// validate checks the block in Y0 after the one in Y14, adding errors to Y12; it leaves the byte three before each
// in Y1, one before in Y2 and two before in Y3.
const validate = `	// Check the block (Keiser and Lemire): Y1 the byte three before each, Y2 one before, Y3 two before.
	VPERM2I128     $0x21, Y0, Y14, Y1
	VPALIGNR       $15, Y1, Y0, Y2
	VPALIGNR       $14, Y1, Y0, Y3
	VPALIGNR       $13, Y1, Y0, Y1
	VBROADCASTI128 K_T1, Y8
	VBROADCASTI128 K_T2, Y9
	VBROADCASTI128 K_T3, Y10
	VPSRLW         $4, Y2, Y4
	VPAND          Y11, Y4, Y4
	VPSHUFB        Y4, Y8, Y4
	VPAND          Y11, Y2, Y5
	VPSHUFB        Y5, Y9, Y5
	VPSRLW         $4, Y0, Y6
	VPAND          Y11, Y6, Y6
	VPSHUFB        Y6, Y10, Y6
	VPAND          Y5, Y4, Y4
	VPAND          Y6, Y4, Y4
	VPSUBUSB       K_S60, Y3, Y5
	VPSUBUSB       K_S70, Y1, Y6
	VPOR           Y6, Y5, Y5
	VPAND          K_B80, Y5, Y5
	VPXOR          Y5, Y4, Y4
	VPOR           Y4, Y12, Y12
`

// setupAVX2 loads the constants kernelAVX2 keeps in registers: Y11 the low nibble, Y13 C0, Y15 zeros.
const setupAVX2 = `	VPXOR   Y15, Y15, Y15
	VMOVDQU K_NIB, Y11
	VMOVDQU K_C0, Y13
`

// setupAVX512 is setupAVX2 and the tables of the validation in Y16 to Y18.
const setupAVX512 = setupAVX2 + `	VBROADCASTI32X4 K_T1, Y16
	VBROADCASTI32X4 K_T2, Y17
	VBROADCASTI32X4 K_T3, Y18
`

// kernelAVX2 converts the text at SI (BX bytes, BX > 0) to Latin-1 at DI, or to UTF-16 at the pointer in local
// wide; AX the result (bytes, ^units or wireInvalid); then a jump to {p}done. DI must equal local start on entry,
// and the constants of setupAVX2 be in their registers.
func kernelAVX2(p string) string {
	return sub(`	XORQ    DX, DX
	VPXOR   Y14, Y14, Y14
	VPXOR   Y12, Y12, Y12

{p}latin1:
	MOVQ BX, AX
	SUBQ DX, AX
	JLE  {p}latin1Done
`+load32(p, "l", "lbody")+`
{p}lbody:
	VPMOVMSKB Y0, R8
	TESTL     R8, R8
	JNZ       {p}lchars
	// ASCII: no char of the block before may be cut.
	VPSUBUSB  K_TAIL, Y14, Y4
	VPOR      Y4, Y12, Y12
	VMOVDQU   Y0, (DI)
	POPCNTL   R13, R8
	ADDQ      R8, DI
	VMOVDQA   Y0, Y14
	ADDQ      $32, DX
	JMP       {p}latin1

{p}lchars:
	// A byte above C3 (a char above U+00FF, or not UTF-8): UTF-16, from the start.
	VPSUBUSB  K_C3, Y0, Y4
	VPTEST    Y4, Y4
	JNZ       {p}toUTF16
	// Its bytes are ASCII, leads C2 and C3 and continuations: it is valid when the continuations are exactly the
	// bytes after the leads, and there are no C0 or C1.
	VPERM2I128 $0x21, Y0, Y14, Y1
	VPALIGNR  $15, Y1, Y0, Y2    // the byte before each
	VPAND     K_FE, Y0, Y7
	VPCMPEQB  K_C2, Y7, Y4       // the leads
	VPCMPEQB  Y13, Y7, Y7        // C0 and C1
	VPOR      Y7, Y12, Y12
	VPAND     K_FE, Y2, Y5
	VPCMPEQB  K_C2, Y5, Y5       // after a lead
	VPCMPGTB  Y0, Y13, Y6        // continuations
	VPXOR     Y6, Y5, Y5
	VPOR      Y5, Y12, Y12
	VPCMPEQB  K_C3, Y2, Y5
	VPAND     K_B40, Y5, Y5
	VPADDB    Y5, Y0, Y6         // the bytes: 40 more after C3
	VPMOVMSKB Y4, R8
	NOTL      R8
	ANDL      R13, R8            // kept
	MOVL      R8, R9
	ANDL      $0xff, R9
	MOVL      R8, R10
	SHRL      $8, R10
	ANDL      $0xff, R10
	MOVL      R8, R11
	SHRL      $16, R11
	ANDL      $0xff, R11
	MOVL      R8, R12
	SHRL      $24, R12
	LEAQ      ·narrowLo(SB), AX
	LEAQ      ·narrowHi(SB), CX
	VMOVQ     (AX)(R9*8), X4
	VPINSRQ   $1, (CX)(R10*8), X4, X4
	VMOVQ     (AX)(R11*8), X7
	VPINSRQ   $1, (CX)(R12*8), X7, X7
	VINSERTI128 $1, X7, Y4, Y4
	VPSHUFB   Y4, Y6, Y6
	POPCNTL   R9, R9
	POPCNTL   R10, R10
	POPCNTL   R11, R11
	POPCNTL   R12, R12
	VMOVDQU   X6, (DI)
	VPEXTRQ   $1, X6, CX
	MOVQ      CX, (DI)(R9*1)
	ADDQ      R9, DI
	ADDQ      R10, DI
	VEXTRACTI128 $1, Y6, X7
	VMOVDQU   X7, (DI)
	VPEXTRQ   $1, X7, CX
	MOVQ      CX, (DI)(R11*1)
	ADDQ      R11, DI
	ADDQ      R12, DI
	VMOVDQA   Y0, Y14
	ADDQ      $32, DX
	JMP       {p}latin1

{p}latin1Done:
	VPSUBUSB K_TAIL, Y14, Y4
	VPOR     Y4, Y12, Y12
	VPTEST   Y12, Y12
	JNZ      {p}invalid
	MOVQ     DI, AX
	SUBQ     start-8(SP), AX
	JMP      {p}done

{p}toUTF16:
	// From the start again, as UTF-16: the block in Y0 when it is the first.
	MOVQ  wide-16(SP), DI
	VPXOR Y14, Y14, Y14
	VPXOR Y12, Y12, Y12
	TESTQ DX, DX
	JZ    {p}wchars
	XORQ  DX, DX

{p}wide:
	MOVQ BX, AX
	SUBQ DX, AX
	JLE  {p}wideDone
`+load32(p, "w", "wbody")+`
{p}wbody:
	VPMOVMSKB Y0, R8
	TESTL     R8, R8
	JNZ       {p}wchars
	VPSUBUSB  K_TAIL, Y14, Y4
	VPOR      Y4, Y12, Y12
	VPMOVZXBW X0, Y4
	VEXTRACTI128 $1, Y0, X5
	VPMOVZXBW X5, Y5
	VMOVDQU   Y4, (DI)
	VMOVDQU   Y5, 32(DI)
	POPCNTL   R13, R8
	LEAQ      (DI)(R8*2), DI
	VMOVDQA   Y0, Y14
	ADDQ      $32, DX
	JMP       {p}wide

{p}wchars:
`+validate+`	VMOVDQA   Y0, Y14
	VPCMPGTB  Y0, Y13, Y4        // b0 a continuation
	VPCMPGTB  Y2, Y13, Y5        // b1 a continuation
	VPAND     K_E0, Y2, Y6
	VPCMPEQB  Y13, Y6, Y6        // b1 the lead of 2 bytes
	VPCMPGTB  Y0, Y15, Y7        // b0 not ASCII
	VPOR      Y6, Y5, Y5
	VPAND     Y4, Y5, Y5         // b0 ends a char of 2 or more bytes, or is a third byte
	VPANDN    Y7, Y5, Y5         // dropped: the rest of the bytes not ASCII
	VPMOVMSKB Y5, R8
	NOTL      R8
	ANDL      R13, R8            // kept
	// The low bytes: b0 for ASCII, else (b0 & 3F) | b1 << 6.
	VPAND     K_B3F, Y0, Y4
	VPSLLW    $6, Y2, Y5
	VPAND     Y13, Y5, Y5
	VPOR      Y5, Y4, Y4
	VPBLENDVB Y7, Y4, Y0, Y4
	// The high bytes: 0 for ASCII, (b1 >> 2) & 0F after the lead of 2 bytes, and that | b2 << 4 else.
	VPSRLW    $2, Y2, Y5
	VPAND     Y11, Y5, Y5
	VPSLLW    $4, Y3, Y8
	VPAND     K_F0, Y8, Y8
	VPOR      Y5, Y8, Y8
	VPBLENDVB Y6, Y5, Y8, Y8
	VPAND     Y7, Y8, Y8
	// Surrogates: b2 the lead of 4 bytes (the high one), or b3 (the low one).
	VPAND     K_F8, Y3, Y9
	VPCMPEQB  K_F0, Y9, Y9
	VPAND     K_F8, Y1, Y10
	VPCMPEQB  K_F0, Y10, Y10
	VPOR      Y10, Y9, Y6
	VPTEST    Y6, Y6
	JZ        {p}wpack
	// The high surrogate: D800 + ((b2 & 7) << 8 | (b1 & 3F) << 2 | (b0 >> 4) & 3) - 40.
	VPAND     K_B3F, Y2, Y6
	VPSLLW    $2, Y6, Y6
	VPSRLW    $4, Y0, Y7
	VPAND     K_B03, Y7, Y7
	VPOR      Y7, Y6, Y6
	VPSUBB    K_B40, Y6, Y7
	VPBLENDVB Y9, Y7, Y4, Y4
	VPAND     Y13, Y6, Y6
	VPCMPEQB  Y15, Y6, Y6        // the borrow
	VPAND     K_B07, Y3, Y7
	VPADDB    K_D8, Y7, Y7
	VPADDB    Y6, Y7, Y7
	VPBLENDVB Y9, Y7, Y8, Y8
	// The low surrogate: DC00 | (b1 & 0F) << 6 | b0 & 3F.
	VPAND     K_B03, Y5, Y7
	VPOR      K_DC, Y7, Y7
	VPBLENDVB Y10, Y7, Y8, Y8

{p}wpack:
	VPUNPCKLBW Y8, Y4, Y5        // the units of positions 0 to 7 and 16 to 23
	VPUNPCKHBW Y8, Y4, Y6        // 8 to 15 and 24 to 31
	MOVL      R8, R9
	ANDL      $0xff, R9
	MOVL      R8, R10
	SHRL      $8, R10
	ANDL      $0xff, R10
	MOVL      R8, R11
	SHRL      $16, R11
	ANDL      $0xff, R11
	MOVL      R8, R12
	SHRL      $24, R12
	LEAQ      ·wideShuf(SB), AX
	MOVL      R9, CX
	SHLL      $4, CX
	VMOVDQU   (AX)(CX*1), X7
	MOVL      R11, CX
	SHLL      $4, CX
	VINSERTI128 $1, (AX)(CX*1), Y7, Y7
	VPSHUFB   Y7, Y5, Y5
	MOVL      R10, CX
	SHLL      $4, CX
	VMOVDQU   (AX)(CX*1), X7
	MOVL      R12, CX
	SHLL      $4, CX
	VINSERTI128 $1, (AX)(CX*1), Y7, Y7
	VPSHUFB   Y7, Y6, Y6
	POPCNTL   R9, R9
	POPCNTL   R10, R10
	POPCNTL   R11, R11
	POPCNTL   R12, R12
	VMOVDQU   X5, (DI)
	LEAQ      (DI)(R9*2), DI
	VMOVDQU   X6, (DI)
	LEAQ      (DI)(R10*2), DI
	VEXTRACTI128 $1, Y5, X7
	VMOVDQU   X7, (DI)
	LEAQ      (DI)(R11*2), DI
	VEXTRACTI128 $1, Y6, X7
	VMOVDQU   X7, (DI)
	LEAQ      (DI)(R12*2), DI
	ADDQ      $32, DX
	JMP       {p}wide

{p}wideDone:
	VPSUBUSB K_TAIL, Y14, Y4
	VPOR     Y4, Y12, Y12
	VPTEST   Y12, Y12
	JNZ      {p}invalid
	MOVQ     DI, AX
	SUBQ     wide-16(SP), AX
	SHRQ     $1, AX
	NOTQ     AX
	JMP      {p}done

{p}invalid:
	MOVQ $0x7fffffffffffffff, AX
	JMP  {p}done
`, "p", p)
}

// load512 is load32 with AVX-512: the last block read under a mask (no fault past the text).
func load512(p, l, body string) string {
	return sub(`	CMPQ    AX, $32
	JB      {p}{l}tail
	MOVL    $0xffffffff, R13
	VMOVDQU (SI)(DX*1), Y0
	JMP     {p}{body}

{p}{l}tail:
	// Fewer than 32 bytes left: R13 the mask of those, read alone (masked, so no fault past them).
	MOVL          $1, R13
	MOVQ          AX, CX
	SHLL          CX, R13
	DECL          R13
	KMOVD         R13, K1
	VMOVDQU8.Z    (SI)(DX*1), K1, Y0
	JMP           {p}{body}
`, "p", p, "l", l, "body", body)
}

// kernelAVX512 is kernelAVX2 with AVX-512 (BW, VL and VBMI2): masked loads for the last block, mask registers for
// the choices, the chars kept compressed in a register (no tables).
func kernelAVX512(p string) string {
	k := kernelAVX2(p)
	k = replaceOnce(k, load32(p, "l", "lbody"), load512(p, "l", "lbody"))
	k = replaceOnce(k, load32(p, "w", "wbody"), load512(p, "w", "wbody"))
	// Latin-1 text needs no full validation: its bytes are ASCII, leads C2 and C3 and continuations, and it is valid
	// when the continuations are exactly the bytes after the leads (and there are no C0 or C1). R12 carries the end
	// of the block before: bit 0 a lead, bit 1 C3.
	k = replaceOnce(k, "\tVPXOR   Y12, Y12, Y12\n", "\tVPXOR   Y12, Y12, Y12\n\tXORL    R12, R12\n")
	// The tables of the validation in Y16 to Y18 (setupAVX512).
	k = strings.ReplaceAll(k, `	VBROADCASTI128 K_T1, Y8
	VBROADCASTI128 K_T2, Y9
	VBROADCASTI128 K_T3, Y10
`, "")
	k = strings.ReplaceAll(k, "VPSHUFB        Y4, Y8, Y4", "VPSHUFB        Y4, Y16, Y4")
	k = strings.ReplaceAll(k, "VPSHUFB        Y5, Y9, Y5", "VPSHUFB        Y5, Y17, Y5")
	k = strings.ReplaceAll(k, "VPSHUFB        Y6, Y10, Y6", "VPSHUFB        Y6, Y18, Y6")
	k = replaceOnce(k, `	// ASCII: no char of the block before may be cut.
	VPSUBUSB  K_TAIL, Y14, Y4
	VPOR      Y4, Y12, Y12
	VMOVDQU   Y0, (DI)
	POPCNTL   R13, R8
	ADDQ      R8, DI
	VMOVDQA   Y0, Y14
`, sub(`	// ASCII: no char of the block before may be cut.
	TESTL     R12, R12
	JNZ       {p}invalid
	VMOVDQU   Y0, (DI)
	POPCNTL   R13, R8
	ADDQ      R8, DI
`, "p", p))
	k = replaceSpan(k, p+"lchars:", "\t// Its bytes are ASCII", "\tJMP       "+p+"latin1\n", sub(`	VPCMPGTB    Y0, Y13, K1        // continuations
	VPCMPEQB    K_C3, Y0, K2       // C3
	VPAND       K_FE, Y0, Y4
	VPCMPEQB    K_C2, Y4, K3       // the leads
	KMOVD       K1, R9
	KMOVD       K3, R10
	KMOVD       K2, R11
	MOVL        R12, AX
	ANDL        $1, AX
	LEAQ        (AX)(R10*2), AX
	XORL        R9, AX
	JNZ         {p}invalid         // a lead without its continuation, or a continuation without its lead
	MOVL        R10, AX
	ORL         R9, AX
	NOTL        AX
	ANDL        R8, AX
	JNZ         {p}invalid         // C0 or C1
	MOVL        R12, CX
	SHRL        $1, CX
	LEAQ        (CX)(R11*2), CX    // the bytes after C3
	KMOVD       CX, K4
	MOVL        R10, R12
	SHRL        $31, R12
	SHRL        $31, R11
	LEAL        (R12)(R11*2), R12
	VMOVDQA     Y0, Y6
	VPADDB      K_B40, Y0, K4, Y6  // the bytes: 40 more after C3
	NOTL        R10
	ANDL        R13, R10           // kept: all but the leads
	KMOVD       R10, K2
	VPCOMPRESSB Y6, K2, Y6
	VMOVDQU     Y6, (DI)
	POPCNTL     R10, R10
	ADDQ        R10, DI
	ADDQ        $32, DX
	JMP         {p}latin1
`, "p", p))
	k = replaceOnce(k, sub(`{p}latin1Done:
	VPSUBUSB K_TAIL, Y14, Y4
	VPOR     Y4, Y12, Y12
	VPTEST   Y12, Y12
	JNZ      {p}invalid
`, "p", p), sub(`{p}latin1Done:
	TESTL    R12, R12
	JNZ      {p}invalid
`, "p", p))
	k = replaceOnce(k, `	VPMOVZXBW X0, Y4
	VEXTRACTI128 $1, Y0, X5
	VPMOVZXBW X5, Y5
	VMOVDQU   Y4, (DI)
	VMOVDQU   Y5, 32(DI)
`, `	VPMOVZXBW Y0, Z4
	VMOVDQU64 Z4, (DI)
`)
	k = replaceSpan(k, p+"wchars:\n", "\tVMOVDQA   Y0, Y14\n", "\n"+p+"wpack:\n", sub(`	VMOVDQA    Y0, Y14
	VPCMPGTB   Y0, Y13, K3        // b0 a continuation
	VPCMPGTB   Y2, Y13, K4        // b1 a continuation
	VPAND      K_E0, Y2, Y6
	VPCMPEQB   Y13, Y6, K6        // b1 the lead of 2 bytes
	VPMOVB2M   Y0, K7             // b0 not ASCII
	KORD       K6, K4, K4
	KANDD      K3, K4, K4         // b0 ends a char of 2 or more bytes, or is a third byte
	KNOTD      K7, K5
	KORD       K5, K4, K4         // kept: those and ASCII
	KMOVD      K4, R8
	ANDL       R13, R8
	// The low bytes: b0 for ASCII, else (b0 & 3F) | b1 << 6.
	VPAND      K_B3F, Y0, Y4
	VPSLLW     $6, Y2, Y5
	VPAND      Y13, Y5, Y5
	VPOR       Y5, Y4, Y4
	VPBLENDMB  Y4, Y0, K7, Y4
	// The high bytes: 0 for ASCII, (b1 >> 2) & 0F after the lead of 2 bytes, and that | b2 << 4 else.
	VPSRLW     $2, Y2, Y5
	VPAND      Y11, Y5, Y5
	VPSLLW     $4, Y3, Y8
	VPAND      K_F0, Y8, Y8
	VPOR       Y5, Y8, Y8
	VPBLENDMB  Y5, Y8, K6, Y8
	VMOVDQU8.Z Y8, K7, Y8
	// Surrogates: b2 the lead of 4 bytes (the high one), or b3 (the low one).
	VPAND      K_F8, Y3, Y9
	VPCMPEQB   K_F0, Y9, K1
	VPAND      K_F8, Y1, Y10
	VPCMPEQB   K_F0, Y10, K2
	KORTESTD   K1, K2
	JZ         {p}wpack
	// The high surrogate: D800 + ((b2 & 7) << 8 | (b1 & 3F) << 2 | (b0 >> 4) & 3) - 40.
	VPAND      K_B3F, Y2, Y6
	VPSLLW     $2, Y6, Y6
	VPSRLW     $4, Y0, Y7
	VPAND      K_B03, Y7, Y7
	VPOR       Y7, Y6, Y6
	VPSUBB     K_B40, Y6, Y7
	VPBLENDMB  Y7, Y4, K1, Y4
	VPAND      Y13, Y6, Y6
	VPCMPEQB   Y15, Y6, Y6        // the borrow
	VPAND      K_B07, Y3, Y7
	VPADDB     K_D8, Y7, Y7
	VPADDB     Y6, Y7, Y7
	VPBLENDMB  Y7, Y8, K1, Y8
	// The low surrogate: DC00 | (b1 & 0F) << 6 | b0 & 3F.
	VPAND      K_B03, Y5, Y7
	VPOR       K_DC, Y7, Y7
	VPBLENDMB  Y7, Y8, K2, Y8

{p}wpack:
`, "p", p))
	k = replaceSpan(k, p+"wpack:\n", "\tVPUNPCKLBW", "\tJMP       "+p+"wide\n", sub(`	VPMOVZXBW   Y4, Z4
	VPMOVZXBW   Y8, Z5
	VPSLLW      $8, Z5, Z5
	VPORQ       Z5, Z4, Z4
	KMOVD       R8, K2
	VPCOMPRESSW Z4, K2, Z4
	VMOVDQU64   Z4, (DI)
	POPCNTL     R8, R8
	LEAQ        (DI)(R8*2), DI
	ADDQ        $32, DX
	JMP         {p}wide
`, "p", p))
	if strings.Contains(k, "narrow") || strings.Contains(k, "wideShuf") {
		log.Fatal("wiregen: a table left in the AVX-512 kernel")
	}
	return k
}

func single(name, setup string, kern func(string) string, p string) string {
	return sub(`
// func {name}(dst unsafe.Pointer, i int, src unsafe.Pointer, n int) int
TEXT ·{name}(SB), NOSPLIT, $16-40
	MOVQ src+16(FP), SI
	MOVQ i+8(FP), DX
	ADDQ DX, SI              // the text from i on
	MOVQ n+24(FP), BX
	SUBQ DX, BX              // its length
	MOVQ dst+0(FP), DI
	LEAQ (DI)(DX*2), AX
	MOVQ AX, wide-16(SP)     // UTF-16 goes to dst+2*i
	ADDQ DX, DI              // Latin-1 to dst+i
	MOVQ DI, start-8(SP)
`, "name", name) + setup + kern(p) + sub(`
{p}done:
	MOVQ AX, ret+32(FP)
	VZEROUPPER
	RET
`, "p", p)
}

func many(name, setup string, kern func(string) string, p string) string {
	return sub(`
// func {name}(dst unsafe.Pointer, room int, strs unsafe.Pointer, count int, ptrs bool) (done, written int)
//
// It writes strings from strs (count of them: strings, or pointers to them when ptrs, nil the null string) at dst
// (room bytes), each with its header, while each has room for 4+2*len+64 bytes and is WTF-8 of fewer than 2^30
// bytes; it returns how many it wrote and the bytes they took.
TEXT ·{name}(SB), NOSPLIT, $32-56
	MOVQ dst+0(FP), AX
	MOVQ AX, out-24(SP)
	ADDQ room+8(FP), AX
	MOVQ AX, end-32(SP)
	XORQ R14, R14           // the strings done (R14 is free in ABI0)
`+setup+`
{p}next:
	MOVQ R14, CX
	CMPQ CX, count+24(FP)
	JAE  {p}finish
	MOVQ strs+16(FP), R8
	CMPB ptrs+32(FP), $0
	JEQ  {p}value
	MOVQ (R8)(CX*8), R8
	TESTQ R8, R8
	JNZ  {p}header
	// nil: the null string.
	MOVQ out-24(SP), DI
	LEAQ 4(DI), AX
	CMPQ AX, end-32(SP)
	JA   {p}finish
	MOVL $0xffffffff, (DI)
	MOVQ AX, out-24(SP)
	INCQ R14
	JMP  {p}next

{p}value:
	SHLQ $4, CX
	ADDQ CX, R8

{p}header:
	MOVQ (R8), SI
	MOVQ 8(R8), BX
	MOVQ out-24(SP), DI
	TESTQ BX, BX
	JNZ  {p}text
	LEAQ 4(DI), AX
	CMPQ AX, end-32(SP)
	JA   {p}finish
	MOVL $0, (DI)
	MOVQ AX, out-24(SP)
	INCQ R14
	JMP  {p}next

{p}text:
	CMPQ BX, $0x40000000
	JAE  {p}finish
	LEAQ 68(DI)(BX*2), AX
	CMPQ AX, end-32(SP)
	JA   {p}finish
	ADDQ $4, DI
	MOVQ DI, start-8(SP)
	MOVQ DI, wide-16(SP)
`, "name", name, "p", p) + kern(p) + sub(`
{p}done:
	MOVQ out-24(SP), DI
	MOVQ $0x7fffffffffffffff, CX
	CMPQ AX, CX
	JEQ  {p}finish
	TESTQ AX, AX
	JS   {p}store16
	MOVL AX, CX
	NOTL CX
	MOVL CX, (DI)
	LEAQ 4(DI)(AX*1), DI
	MOVQ DI, out-24(SP)
	INCQ R14
	JMP  {p}next

{p}store16:
	NOTQ AX
	MOVL AX, (DI)
	LEAQ 4(DI)(AX*2), DI
	MOVQ DI, out-24(SP)
	INCQ R14
	JMP  {p}next

{p}finish:
	MOVQ R14, AX
	MOVQ AX, done+40(FP)
	MOVQ out-24(SP), AX
	SUBQ dst+0(FP), AX
	MOVQ AX, written+48(FP)
	VZEROUPPER
	RET
`, "p", p)
}

