#!/usr/bin/env bash
# The Unity benchmark's inputs (Test.Runtime.Burst.BurstBenchmark), from the .NET suite (runtimes/csharp/benchmarks),
# written into this project and ignored by Git:
#   Assets/Test/Runtime/Burst/Cases/     the benchmark models (Nino.Benchmark.Schema's files: Nino.Benchmark's Fixtures/
#                                        and Workloads/*Models.cs, with CompetitorAttributes.cs's stand-ins) and
#                                        BenchCases.cs, the case list: one line per case whose value has a .NET type
#                                        (cases.json; the BCL cases, held as object, and the C# union cases, which need C# 15, are left out), which instantiates
#                                        the benchmark's generic calls for IL2CPP, and registers the closed generic
#                                        [NinoType]s the values hold (generics.txt), which the player reads unwritten
#   Assets/StreamingAssets/NinoBench/    each case's Nino bytes (Nino.Benchmark --write-data: <Case>.nino.bin), which
#                                        the player reads, writes back and times
# unity.yml runs it before the benchmark's player build; a new C# case needs no Unity edit. Needs the .NET SDK
# (runtimes/csharp/global.json) and python3.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
unity=$(cd "$here/.." && pwd)
csharp=$(cd "$unity/../.." && pwd)
bench=$csharp/benchmarks
cases=$unity/Assets/Test/Runtime/Burst/Cases
assets=$unity/Assets/StreamingAssets/NinoBench
data=$(mktemp -d)
trap 'rm -rf "$data"' EXIT

dotnet build -c Release "$bench/Nino.Benchmark" > /dev/null
dotnet "$bench/Nino.Benchmark/bin/Release/net11.0/Nino.Benchmark.dll" --write-data "$data"

rm -rf "${cases:?}" "${assets:?}"
mkdir -p "$cases" "$assets"
# The files Nino.Benchmark.Schema.csproj compiles, as it lists them.
for f in "$bench"/Nino.Benchmark/Fixtures/*.cs; do
  case $(basename "$f") in CaseFormats.cs | ProtobufModel.cs) continue ;; esac
  cp "$f" "$cases/"
done
cp "$bench"/Nino.Benchmark/Workloads/*Models.cs "$bench/Nino.Benchmark/Workloads/Common.cs" \
  "$bench/Nino.Benchmark.Schema/CompetitorAttributes.cs" "$cases/"
cp "$data"/*.nino.bin "$assets/"

python3 - "$data/cases.json" "$data/generics.txt" "$cases/BenchCases.cs" <<'PY'
import json, re, sys

cases = json.load(open(sys.argv[1]))
generics = open(sys.argv[2]).read().split()

def csharp(name):
    # A runtime-form name (System.Collections.Generic.List<System.Int32>, Outer+Inner[]) as C# with global::.
    return re.sub(r"(?<![\w.:])([A-Za-z_][\w.]*)", r"global::\1", name.replace("+", "."))

# The closed generic [NinoType]s the values hold, registered before anything is read: the player reads them without
# having written them (NinoPolymorphic.TryRegister).
lines = [f'            global::Nino.Core.NinoPolymorphic.TryRegister<{csharp(g)}>();' for g in generics]
lines += [f'            cases.Add(Load<{csharp(c["type"])}>("{c["case"]}", {str(c["old"]).lower()}));'
         for c in cases if c["type"] != "System.Object" and not c.get("union")]
with open(sys.argv[3], "w") as f:
    f.write(f"""// Generated by bench/generate.sh from Nino.Benchmark --write-data's cases.json: do not edit.
#if NINO_BURST && NINO_UNITY_BENCH
namespace Test.Runtime.Burst
{{
    public partial class BurstBenchmark
    {{
        private static void AddCases(System.Collections.Generic.List<Case> cases)
        {{
{chr(10).join(lines)}
        }}
    }}
}}
#endif
""")
print(f"{len(lines) - len(generics)} cases and {len(generics)} closed generic types in {sys.argv[3]}")
PY
