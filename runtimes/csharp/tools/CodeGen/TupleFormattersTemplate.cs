        /// <summary>
        /// What a value tuple of two does on a run, composed from its items as a <c>KeyValuePair</c> is
        /// (<c>NinoItems</c>): the cursor form of a run holding strings and the run loop of a polymorphic second item.
        /// </summary>
        private static void AppendPairRuns(StringBuilder sb, string type)
        {
            sb.Append("\n");
            sb.Append("        // Where each item lies in the tuple: JIT-time constants, also in code shared over a class.\n");
            foreach (int i in new[] { 1, 2 })
                AppendOffset(sb, type, i);

            const string pairs = "NinoItems";
            const string items = "<T1, T2, TF1, TF2>";
            sb.Append("        // A run of tuples with a string among their items through the string run kernels, one call per run; a\n");
            sb.Append("        // polymorphic second item's run loop, the first written by it.\n");
            sb.Append($"        bool INinoFormatter.HasCursor => {pairs}.Cursor{items}(Offset1, Offset2);\n");
            sb.Append("\n");
            sb.Append("        Writer INinoFormatter.WriteStrings(scoped NinoRun run, Writer writer) =>\n");
            sb.Append($"            {pairs}.WritePair{items}(run, Offset1, Offset2, writer);\n");
            sb.Append("\n");
            sb.Append("        int INinoFormatter.ReadStrings(scoped NinoRun run, ref byte data, int end) =>\n");
            sb.Append($"            {pairs}.ReadPair{items}(run, Offset1, Offset2, ref data, end);\n");
            sb.Append("\n");
            sb.Append($"        bool INinoFormatter.HasRunLoop => {pairs}.RunLoop{items}(Offset1, Offset2);\n");
            sb.Append("\n");
            sb.Append("        [MethodImpl(MethodImplOptions.AggressiveInlining)]\n");
            sb.Append("        void INinoFormatter.WriteRun(NinoRun run, ref Writer writer) =>\n");
            sb.Append($"            {pairs}.WriteRun{items}(run, Offset1, Offset2, ref writer);\n");
        }

        private static void AppendTuple(StringBuilder sb, Shape s)
        {
            string type = $"Tuple<{s.Types}>";
            string formatter = $"TupleFormatter<{s.TypeParameters}>";
            string noReferences = string.Join(" && ",
                s.Items.Select(i => $"!NinoUnsafe.IsReferenceOrContainsReferences<{s.Type(i)}>()"));
            sb.Append($"    /// <summary><c>Tuple&lt;{s.Types}&gt;</c>: a presence byte, then the items in order (one block where every item\n");
            sb.Append("    /// is raw or a block).</summary>\n");
            sb.Append($"    public struct TupleFormatter<{s.TypeParameters}> : INinoFormatter<{type}>\n");
            AppendConstraints(sb, s);
            sb.Append("    {\n");
            AppendSizes(sb, s, noReferences);
            AppendBodyTraits(sb, s);
            sb.Append($"        public void Serialize({type} value, ref Writer writer)\n");
            sb.Append("        {\n");
            sb.Append("            if (!writer.WritePresence(value))\n");
            sb.Append("                return;\n");
            sb.Append("\n");
            sb.Append("            if (Fixed)\n");
            sb.Append("            {\n");
            sb.Append("                ref byte destination = ref writer.Reserve(Size);\n");
            AppendItemWrites(sb, s, "                ", "value", "destination");
            sb.Append("                return;\n");
            sb.Append("            }\n");
            sb.Append("\n");
            foreach (int i in s.Items)
                sb.Append($"            default(TF{i}).Serialize(value.Item{i}, ref writer);\n");
            sb.Append("        }\n");
            sb.Append("\n");
            sb.Append($"        public void Deserialize(ref Reader reader, ref {type} value)\n");
            sb.Append("        {\n");
            sb.Append("            // A tuple dropped (null in the data, or replaced below) recycles its items.\n");
            sb.Append("            if (!reader.ReadPresent())\n");
            sb.Append("            {\n");
            sb.Append($"                NinoRecycler.Discard<{type}, {formatter}>(ref value);\n");
            sb.Append("                return;\n");
            sb.Append("            }\n");
            sb.Append("\n");
            sb.Append("            // Tuples are immutable: the items are read into locals and the tuple is replaced.\n");
            foreach (int i in s.Items)
                sb.Append($"            T{i} item{i} = default;\n");
            sb.Append("            if (Fixed)\n");
            sb.Append("            {\n");
            sb.Append("                ref byte source = ref reader.ReadBlock(Size);\n");
            foreach (int i in s.Items)
                sb.Append($"                {s.Call("ReadItem", i)}(ref item{i}, ref {s.At("source", i)});\n");
            sb.Append("            }\n");
            sb.Append("            else\n");
            sb.Append("            {\n");
            foreach (int i in s.Items)
                sb.Append($"                default(TF{i}).Deserialize(ref reader, ref item{i});\n");
            sb.Append("            }\n");
            sb.Append("\n");
            sb.Append($"            NinoRecycler.Replace<{type}, {formatter}>(ref value, new {type}({string.Join(", ", s.Items.Select(i => $"item{i}"))}));\n");
            sb.Append("        }\n");
            AppendRecycling(sb, s, type);
            sb.Append("    }\n");
        }
