using System.Linq;
using System.Text;
using Nino.Generator.Common;
using static Nino.Generator.Generation.Emit.MemberCode;
using static Nino.Generator.Generation.TypeNames;

namespace Nino.Generator.Generation.Emit;

/// <summary>Emits the source file of one type's formatter.</summary>
internal static class FormatterEmitter
{
    public const string Header = "// <auto-generated/>\n#nullable disable\n#pragma warning disable\n\n";

    public static string Emit(TypeModel m)
    {
        var names = new FormatterNames(m);
        var w = new CodeWriter(4096, indent: 1);
        EmitFormatter(w, m, names);
        string body = w.ToString();

        var sb = new StringBuilder(body.Length + 1024);
        sb.Append(Header);
        sb.Append(LayoutEmitter.Emit(m)).Append('\n');
        sb.Append("namespace " + GenNamespace + "\n{\n");
        names.WriteAliases(sb);
        sb.Append(body);
        sb.Append("}\n");
        if (m.PartialDeclarations.Length > 0)
            sb.Append(AccessorEmitter.EmitPartial(m));
        return sb.ToString();
    }

    private static void EmitFormatter(CodeWriter w, TypeModel m, FormatterNames names)
    {
        string t = m.TypeName;
        string self = m.FormatterName + m.TypeParameterList;
        string iface = m.Kind == FormatterKind.Polymorphic
            ? $"{Core}INinoFormatter<{t}>"
            : $"{Core}INinoBodyFormatter<{t}>";
        if (m.RawStruct)
            iface += $", {Core}INinoRawFormatter";
        if (m.FixedSize)
            iface += $", {Core}INinoFixedSizeFormatter<{t}>";
        if (m.RawBody)
            iface += $", {Core}INinoRawBodyFormatter<{t}>";

        w.Open($"internal {(m.IsDispatchRoot ? "partial " : "")}struct {self} : {iface}{m.Constraints}");
        var body = new BodyEmitter(m, w, names);

        // The forwarders and TypeId are a few bytes of IL, which every runtime inlines without being told to;
        // MethodImpl attributes on them only cost compile time.
        if (m.Kind == FormatterKind.Polymorphic)
        {
            // Behind a reference header, subtypes are dispatched without one of their own.
            if (m.TrackReferences)
                EmitEntryPoints(w, m, $"{Core}NinoPolymorphic<{t}>.SerializeReferenced(value, ref writer)",
                    $"{Core}NinoPolymorphic<{t}>.DeserializeReferenced(reader.UnsafeRead<int>(), ref value, ref reader)");
            else
                EmitDispatchingEntryPoints(w, m, ownId: false);
            w.Line();
            if (m.EmitMembers)
            {
                body.EmitMembersMethods();
                w.Line();
            }

            w.Close();
            return;
        }

        EmitTypeId(w, m);
        w.Line();
        EmitDeferral(w, m);
        w.Line();
        switch (m.Kind)
        {
            case FormatterKind.Struct:
                w.Line($"public void Serialize({t} value, ref {Core}Writer writer) => WriteBody(value, ref writer);");
                w.Line();
                w.Line($"public void Deserialize(ref {t} value, ref {Core}Reader reader) => ReadBody(ref value, ref reader);");
                break;
            case FormatterKind.SealedClass when m.TrackReferences:
                // The reference header already says the object is not null.
                EmitEntryPoints(w, m, $"{Core}NinoObject.WriteBody<{t}, {self}>(value, ref writer)",
                    $"{Core}NinoObject.ReadBody<{t}, {self}>(ref value, ref reader)");
                break;
            case FormatterKind.SealedClass when m.BoundedEntry:
                // The twin's bodies when the depth leaves room for the whole nesting bound (see TypeFacts.DepthBound).
                EmitEntryPoints(w, m,
                    $"{Core}NinoObject.SerializeSealed<{t}, {self}, {self}.__Shallow>(value, ref writer, {m.DepthBound})",
                    $"{Core}NinoObject.DeserializeSealed<{t}, {self}, {self}.__Shallow>(ref value, ref reader, {m.DepthBound})");
                break;
            case FormatterKind.SealedClass:
                EmitEntryPoints(w, m, $"{Core}NinoObject.SerializeSealed{Raw(m)}<{t}, {self}>(value, ref writer)",
                    $"{Core}NinoObject.DeserializeSealed<{t}, {self}>(ref value, ref reader)");
                break;
            case FormatterKind.Class when m.TrackReferences:
                EmitEntryPoints(w, m, $"{Core}NinoObject.SerializeReferenced<{t}, {self}>(value, ref writer)",
                    $"{Core}NinoObject.DeserializeReferenced<{t}, {self}>(ref value, ref reader)");
                break;
            case FormatterKind.Class when m.DispatchesSubtypes:
                EmitDispatchingEntryPoints(w, m, ownId: true);
                break;
            default:
                EmitEntryPoints(w, m, $"{Core}NinoObject.Serialize{Raw(m)}<{t}, {self}>(value, ref writer)",
                    $"{Core}NinoObject.Deserialize<{t}, {self}>(ref value, ref reader)");
                break;
        }

        w.Line();
        if (m.RawStruct)
        {
            body.EmitRawStruct();
        }
        else
        {
            body.EmitWriteBody();
            w.Line();
            body.EmitReadBody();
        }

        if (m.FixedSize)
        {
            w.Line();
            body.EmitFixed();
        }

        if (m.HasTop)
        {
            w.Line();
            EmitTop(w, m, names, body);
        }

        if (m.Shallow)
        {
            if (m.ShallowBodies)
            {
                w.Line();
                body.EmitShallowBodies();
            }

            w.Line();
            EmitShallow(w, m, names, body);
        }

        AccessorEmitter.EmitUnsafeAccessors(w, m);

        w.Close();
    }

    /// <summary>
    /// The formatter the intercepted top-level calls use (see <see cref="TypeModel.HasTop"/>): the same bytes, with
    /// no depth check, and the body inlined into the caller (<see cref="TypeModel.TopInline"/>) or called directly.
    /// </summary>
    private static void EmitTop(CodeWriter w, TypeModel m, FormatterNames names, BodyEmitter body)
    {
        string t = m.TypeName;
        string top = m.FormatterName + ".__Top";
        // An out-of-line body on a local writer (BodyEmitter.LocalWriter, not inlined at the top): the presence
        // byte is written there too, on the local, rather than by the caller on a writer whose address the call
        // takes (each write a load and store of its cursor in memory). The top-level calls that create their writer
        // have it created in a method of its own (__WriteTop, see INinoTopFormatter), where the JIT keeps it in
        // registers and knows it starts empty (no region open, no context) instead of loading it from the caller's
        // memory and storing it back.
        bool serializeTop = !m.TopInline && body.LocalWriter;
        if (serializeTop)
        {
            w.Line(names.NoInline);
            w.Open($"private static void __SerializeTop({t} value, ref {Core}Writer writer)");
            w.Line($"{Core}Writer __w = default;");
            w.Line("writer.CopyTo(ref __w);");
            EmitTopWrite(w, t);
            w.Line("__w.CopyTo(ref writer);");
            w.Close();
            w.Line();
            w.Line(names.NoInline);
            w.Open($"private static void __WriteTop({t} value, {Core}NinoArrayBufferWriter buffer)");
            w.Line($"var __w = new {Core}Writer(buffer);");
            EmitTopWrite(w, t);
            w.Line("__w.Flush();");
            w.Line("__w.ReleaseReferences();");
            w.Close();
            w.Line();
        }

        // The same for the top-level reads of a new value (BodyEmitter.ReadTop): the reader is created in __ReadTop.
        if (body.ReadTop)
        {
            w.Line(names.NoInline);
            w.Open($"private static {t} __ReadTop(global::System.ReadOnlySpan<byte> data)");
            w.Line($"var __r = new {Core}Reader(data);");
            w.Line($"{t} value = null;");
            w.Line($"if (__r.UnsafeRead<byte>() != (byte){NinoWire.Null})");
            w.Indented(() => w.Line($"{(body.SplitFresh ? "__ReadBodyFreshInline" : "__ReadBodyInline")}(ref value, ref __r);"));
            w.Line("__r.ReleaseReferences();");
            w.Line("return value;");
            w.Close();
            w.Line();
        }

        w.Open($"internal struct __Top : {Core}INinoBodyFormatter<{t}>, {Core}INinoTopFormatter<{t}>");
        w.Line("public int TypeId => Id;");
        w.Line($"public int Traits => default({m.FormatterName}).Traits;");
        w.Line($"public {t} Create() => default({m.FormatterName}).Create();");
        w.Line(serializeTop
            ? $"public void Serialize({t} value, ref {Core}Writer writer) => __SerializeTop(value, ref writer);"
            : m.RawBody
                ? $"public void Serialize({t} value, ref {Core}Writer writer) => {Core}NinoObject.SerializeTopRaw<{t}, {m.FormatterName}>(value, ref writer);"
                : $"public void Serialize({t} value, ref {Core}Writer writer) => {Core}NinoObject.SerializeTop<{t}, {top}>(value, ref writer);");
        w.Line(serializeTop
            ? $"public void Write({t} value, {Core}NinoArrayBufferWriter buffer) => __WriteTop(value, buffer);"
            : $"public void Write({t} value, {Core}NinoArrayBufferWriter buffer) => {Core}NinoDirect.Write<{t}, {top}>(value, buffer);");
        w.Line($"public void Deserialize(ref {t} value, ref {Core}Reader reader) => {Core}NinoObject.DeserializeTop<{t}, {top}>(ref value, ref reader);");
        w.Line(body.ReadTop
            ? $"public {t} Read(global::System.ReadOnlySpan<byte> data) => __ReadTop(data);"
            : $"public {t} Read(global::System.ReadOnlySpan<byte> data) => {Core}NinoDirect.Deserialize<{t}, {top}>(data);");

        w.Line(names.Inline);
        w.Line(m.TopInline
            ? $"public void WriteBody({t} value, ref {Core}Writer writer) => __WriteBodyInline(value, ref writer);"
            : $"public void WriteBody({t} value, ref {Core}Writer writer) => default({m.FormatterName}).WriteBody(value, ref writer);");
        w.Line(names.Inline);
        w.Line(m.TopInline
            ? $"public void ReadBody(ref {t} value, ref {Core}Reader reader) => __ReadBodyInline(ref value, ref reader);"
            : $"public void ReadBody(ref {t} value, ref {Core}Reader reader) => default({m.FormatterName}).ReadBody(ref value, ref reader);");
        w.Close();
    }

    /// <summary>The null flag and the body of <c>value</c>, on the local writer <c>__w</c>.</summary>
    private static void EmitTopWrite(CodeWriter w, string t)
    {
        w.Line("if (value == null)");
        w.Indented(() => w.Line($"__w.UnsafeWrite((byte){NinoWire.Null});"));
        w.Open("else");
        w.Line($"__w.UnsafeWrite((byte){NinoWire.NotNull});");
        w.Line("__WriteBodyInline(value, ref __w);");
        w.Close();
    }

    /// <summary>
    /// The twin for where the nesting bound is known to stay below <c>NinoDepth.Inline</c> (see
    /// <see cref="TypeModel.Shallow"/>): the same bytes, with no depth counted or checked, here or in the members
    /// (their formatters' twins). Used by the bodies of other twins, by <see cref="TypeModel.BoundedEntry"/> and by the
    /// intercepted top-level calls.
    /// </summary>
    private static void EmitShallow(CodeWriter w, TypeModel m, FormatterNames names, BodyEmitter body)
    {
        string t = m.TypeName;
        string self = m.FormatterName;
        string twin = self + ".__Shallow";
        w.Open($"internal struct __Shallow : {Core}INinoBodyFormatter<{t}>");
        w.Line("public int TypeId => Id;");
        w.Line($"public int Traits => default({self}).Traits;");
        w.Line($"public {t} Create() => default({self}).Create();");
        if (m.Kind == FormatterKind.Struct)
        {
            w.Line($"public void Serialize({t} value, ref {Core}Writer writer) => WriteBody(value, ref writer);");
            w.Line($"public void Deserialize(ref {t} value, ref {Core}Reader reader) => ReadBody(ref value, ref reader);");
        }
        else
        {
            // The null flag, then the body with no depth check: SerializeTop/DeserializeTop.
            w.Line(m.RawBody
                ? $"public void Serialize({t} value, ref {Core}Writer writer) => {Core}NinoObject.SerializeTopRaw<{t}, {self}>(value, ref writer);"
                : $"public void Serialize({t} value, ref {Core}Writer writer) => {Core}NinoObject.SerializeTop<{t}, {twin}>(value, ref writer);");
            w.Line($"public void Deserialize(ref {t} value, ref {Core}Reader reader) => {Core}NinoObject.DeserializeTop<{t}, {twin}>(ref value, ref reader);");
        }

        w.Line(names.Inline);
        w.Line(m.ShallowBodies
            ? $"public void WriteBody({t} value, ref {Core}Writer writer) => __WriteBodyShallow(value, ref writer);"
            : $"public void WriteBody({t} value, ref {Core}Writer writer) => default({self}).WriteBody(value, ref writer);");
        w.Line(names.Inline);
        if (m.ShallowBodies && body.SplitFresh)
        {
            w.Open($"public void ReadBody(ref {t} value, ref {Core}Reader reader)");
            body.EmitFreshForwarder("__ReadBodyShallow");
            w.Close();
        }
        else
        {
            w.Line(m.ShallowBodies
                ? $"public void ReadBody(ref {t} value, ref {Core}Reader reader) => __ReadBodyShallow(ref value, ref reader);"
                : $"public void ReadBody(ref {t} value, ref {Core}Reader reader) => default({self}).ReadBody(ref value, ref reader);");
        }

        w.Close();
    }

    /// <summary>The suffix of the <c>NinoObject</c> methods for a body that is one raw block (<see cref="TypeModel.RawBody"/>).</summary>
    private static string Raw(TypeModel m) => m.RawBody ? "Raw" : "";

    private static void EmitTypeId(CodeWriter w, TypeModel m)
    {
        if (m.IsGeneric)
        {
            w.Line($"private static readonly int s_typeId = {Core}NinoTypeId.Of(typeof({m.TypeName}));");
            w.Line("public int TypeId => s_typeId;");
            return;
        }

        w.Line($"public const int Id = {m.TypeId}; // FNV-1a of \"{EscapeString(m.IdName)}\"");
        w.Line("public int TypeId => Id;");
    }

    /// <summary>Whether a body nested too deep can be read later, and the empty instance it is read into.</summary>
    private static void EmitDeferral(CodeWriter w, TypeModel m)
    {
        string t = m.TypeName;
        // NinoBody.Nests and NinoBody.Deferrable.
        int traits = (m.Nests ? 1 : 0) | (m.Deferrable ? 2 : 0);
        w.Line($"public int Traits => {traits};");
        if (!m.Deferrable)
        {
            w.Line($"public {t} Create() => default;");
            return;
        }

        var c = m.Construction;
        string create = (c.Factory.Length != 0 ? c.Factory : c.Creator) + "()";
        if (m.Pooled)
            create = t + ".RentFromNinoPool() ?? " + create;
        w.Line($"public {t} Create() => {create};");
    }

    /// <summary>Serialize/Deserialize forwarding to the given calls, behind a reference header when tracked.</summary>
    private static void EmitEntryPoints(CodeWriter w, TypeModel m, string write, string read)
    {
        string t = m.TypeName;
        if (!m.TrackReferences)
        {
            w.Line($"public void Serialize({t} value, ref {Core}Writer writer) => {write};");
            w.Line();
            w.Line($"public void Deserialize(ref {t} value, ref {Core}Reader reader) => {read};");
            return;
        }

        w.Block($"public void Serialize({t} value, ref {Core}Writer writer)", () =>
        {
            w.Line("if (writer.WriteReference(value))");
            w.Indented(() => w.Line($"{write};"));
        });
        w.Line();
        w.Block($"public void Deserialize(ref {t} value, ref {Core}Reader reader)", () =>
        {
            w.Line("if (!reader.ReadReference(ref value, out int __index))");
            w.Indented(() => w.Line("return;"));
            w.Line($"{read};");
            w.Line("reader.EndReference(__index, value);");
        });
    }

    /// <summary>
    /// Type id (0 = null) and body. A class's own type is checked first; subtypes go through the generated dispatch
    /// (<see cref="DispatchEmitter"/>).
    /// </summary>
    private static void EmitDispatchingEntryPoints(CodeWriter w, TypeModel m, bool ownId)
    {
        string t = m.TypeName;
        string self = m.FormatterName;
        // The root's dispatch covers every subtype of this class. Writing needs nothing more (its checks are exact);
        // reading checks that the type the data named is one of this class.
        bool root = m.IsDispatchRoot;
        string write = root ? "__WriteSubtype(value, ref writer)" : $"{m.DispatchRootFormatter}.__WriteSubtype(value, ref writer)";
        string read = root
            ? "__ReadSubtype(id, ref value, ref reader);"
            : $"{m.DispatchRootFormatter}.__ReadSubtype(id, ref {Core}NinoObject.AsBaseSlot<{t}, {m.DispatchRoot}>(ref value), ref reader); {Core}NinoObject.EnsureSubtype<{t}>(value);";
        w.Line($"public void Serialize({t} value, ref {Core}Writer writer)");
        w.Indented(() => w.Line(ownId
            ? $"{{ if (!{Core}NinoObject.TryWriteOwn{Raw(m)}<{t}, {self}>(value, ref writer)) {write}; }}"
            : $"{{ if (value == null) writer.UnsafeWrite({NinoWire.NullTypeId}); else {write}; }}"));
        w.Line();
        w.Line($"public void Deserialize(ref {t} value, ref {Core}Reader reader)");
        w.Indented(() => w.Line(ownId
            ? $"{{ int id = reader.UnsafeRead<int>(); if (!{Core}NinoObject.TryReadOwn<{t}, {self}>(id, ref value, ref reader)) {{ {read} }} }}"
            : $"{{ int id = reader.UnsafeRead<int>(); {read} }}"));
    }

    /// <summary>
    /// The statements that register the formatter (non-generic types), emitted into the registry's dispatch
    /// (<see cref="RegistryEmitter"/>) rather than as a method of the formatter: one method less per type.
    /// </summary>
    public static EquatableArray<string> RegisterStatements(TypeModel m)
    {
        if (m.IsGeneric)
            return new EquatableArray<string>(System.Array.Empty<string>());
        var code = new System.Collections.Generic.List<string>(2);
        // A __Top twin writes the regular top-level calls too (a formatter of fixed size writes them inline).
        if (m.HasTop && !m.FixedSize)
            code.Add($"{Core}NinoFormatterCache<{m.TypeName}>.TryRegisterTop<{m.FormatterName}, {m.FormatterName}.__Top>();");
        else
            code.Add($"{Core}NinoFormatterCache<{m.TypeName}>.{(m.FixedSize ? "TryRegisterFixed" : "TryRegister")}<{m.FormatterName}>();");
        if (m.Kind != FormatterKind.Polymorphic)
            code.Add($"{Core}NinoPolymorphic.{(m.TrackReferences ? "RegisterTracked" : "Register")}<{m.TypeName}, {m.FormatterName}>({m.TypeId});");
        return new EquatableArray<string>(code.ToArray());
    }
}
