using System.Linq;
using System.Text;
using static Nino.Generator.Generation.Emit.MemberCode;
using static Nino.Generator.Generation.TypeNames;

namespace Nino.Generator.Generation.Emit;

/// <summary>Emits the source file of one type's formatter.</summary>
internal static class FormatterEmitter
{
    public const string Header = "// <auto-generated/>\n#nullable disable\n#pragma warning disable\n\n";

    public static string Emit(TypeModel m)
    {
        var names = new FormatterNames(m);
        var w = new CodeWriter(4096, indent: 1);
        EmitFormatter(w, m, names);
        string body = w.ToString();

        var sb = new StringBuilder(body.Length + 1024);
        sb.Append(Header);
        sb.Append("namespace " + GenNamespace + "\n{\n");
        names.WriteAliases(sb);
        sb.Append(body);
        sb.Append("}\n");
        if (m.PartialDeclarations.Length > 0)
            sb.Append(AccessorEmitter.EmitPartial(m));
        return sb.ToString();
    }

    private static void EmitFormatter(CodeWriter w, TypeModel m, FormatterNames names)
    {
        string t = m.TypeName;
        string self = m.FormatterName + m.TypeParameterList;
        string iface = m.Kind == FormatterKind.Polymorphic
            ? $"{Core}INinoFormatter<{t}>"
            : $"{Core}INinoBodyFormatter<{t}>";
        if (m.RawStruct)
            iface += $", {Core}INinoRawFormatter";
        if (m.FixedSize)
            iface += $", {Core}INinoFixedSizeFormatter<{t}>";

        w.Open($"internal {(m.IsDispatchRoot ? "partial " : "")}struct {self} : {iface}{m.Constraints}");
        var body = new BodyEmitter(m, w, names);

        // The forwarders and TypeId are a few bytes of IL, which every runtime inlines without being told to;
        // MethodImpl attributes on them only cost compile time.
        if (m.Kind == FormatterKind.Polymorphic)
        {
            // Behind a reference header, subtypes are dispatched without one of their own.
            if (m.TrackReferences)
                EmitEntryPoints(w, m, $"{Core}NinoPolymorphic<{t}>.SerializeReferenced(value, ref writer)",
                    $"{Core}NinoPolymorphic<{t}>.DeserializeReferenced(reader.UnsafeRead<int>(), ref value, ref reader)");
            else
                EmitDispatchingEntryPoints(w, m, ownId: false);
            w.Line();
            if (m.EmitMembers)
            {
                body.EmitMembersMethods();
                w.Line();
            }

            EmitRegister(w, m);
            w.Close();
            return;
        }

        EmitTypeId(w, m);
        w.Line();
        EmitDeferral(w, m);
        w.Line();
        switch (m.Kind)
        {
            case FormatterKind.Struct:
                w.Line($"public void Serialize({t} value, ref {Core}Writer writer) => WriteBody(value, ref writer);");
                w.Line();
                w.Line($"public void Deserialize(ref {t} value, ref {Core}Reader reader) => ReadBody(ref value, ref reader);");
                break;
            case FormatterKind.SealedClass when m.TrackReferences:
                // The reference header already says the object is not null.
                EmitEntryPoints(w, m, $"{Core}NinoObject.WriteBody<{t}, {self}>(value, ref writer)",
                    $"{Core}NinoObject.ReadBody<{t}, {self}>(ref value, ref reader)");
                break;
            case FormatterKind.SealedClass:
                EmitEntryPoints(w, m, $"{Core}NinoObject.SerializeSealed<{t}, {self}>(value, ref writer)",
                    $"{Core}NinoObject.DeserializeSealed<{t}, {self}>(ref value, ref reader)");
                break;
            case FormatterKind.Class when m.TrackReferences:
                EmitEntryPoints(w, m, $"{Core}NinoObject.SerializeReferenced<{t}, {self}>(value, ref writer)",
                    $"{Core}NinoObject.DeserializeReferenced<{t}, {self}>(ref value, ref reader)");
                break;
            case FormatterKind.Class when m.DispatchesSubtypes:
                EmitDispatchingEntryPoints(w, m, ownId: true);
                break;
            default:
                EmitEntryPoints(w, m, $"{Core}NinoObject.Serialize<{t}, {self}>(value, ref writer)",
                    $"{Core}NinoObject.Deserialize<{t}, {self}>(ref value, ref reader)");
                break;
        }

        w.Line();
        if (m.RawStruct)
        {
            body.EmitRawStruct();
        }
        else
        {
            body.EmitWriteBody();
            w.Line();
            body.EmitReadBody();
        }

        if (m.FixedSize)
        {
            w.Line();
            body.EmitFixed();
        }

        if (m.HasTop)
        {
            w.Line();
            EmitTop(w, m, names);
        }

        AccessorEmitter.EmitUnsafeAccessors(w, m);
        if (!m.IsGeneric)
        {
            w.Line();
            EmitRegister(w, m);
        }

        w.Close();
    }

    /// <summary>
    /// The formatter the intercepted top-level calls use (see <see cref="TypeModel.HasTop"/>): the same bytes, with
    /// no depth check, and the body inlined into the caller (<see cref="TypeModel.TopInline"/>) or called directly.
    /// </summary>
    private static void EmitTop(CodeWriter w, TypeModel m, FormatterNames names)
    {
        string t = m.TypeName;
        string top = m.FormatterName + ".__Top";
        w.Open($"internal struct __Top : {Core}INinoBodyFormatter<{t}>");
        w.Line("public int TypeId => Id;");
        w.Line($"public bool Nests => default({m.FormatterName}).Nests;");
        w.Line($"public bool Deferrable => default({m.FormatterName}).Deferrable;");
        w.Line($"public {t} Create() => default({m.FormatterName}).Create();");
        w.Line($"public void Serialize({t} value, ref {Core}Writer writer) => {Core}NinoObject.SerializeTop<{t}, {top}>(value, ref writer);");
        w.Line($"public void Deserialize(ref {t} value, ref {Core}Reader reader) => {Core}NinoObject.DeserializeTop<{t}, {top}>(ref value, ref reader);");

        w.Line(names.Inline);
        w.Line(m.TopInline
            ? $"public void WriteBody({t} value, ref {Core}Writer writer) => __WriteBodyInline(value, ref writer);"
            : $"public void WriteBody({t} value, ref {Core}Writer writer) => default({m.FormatterName}).WriteBody(value, ref writer);");
        w.Line(names.Inline);
        w.Line(m.TopInline
            ? $"public void ReadBody(ref {t} value, ref {Core}Reader reader) => __ReadBodyInline(ref value, ref reader);"
            : $"public void ReadBody(ref {t} value, ref {Core}Reader reader) => default({m.FormatterName}).ReadBody(ref value, ref reader);");
        w.Close();
    }

    private static void EmitTypeId(CodeWriter w, TypeModel m)
    {
        if (m.IsGeneric)
        {
            w.Line($"private static readonly int s_typeId = {Core}NinoTypeId.Of(typeof({m.TypeName}));");
            w.Line("public int TypeId => s_typeId;");
            return;
        }

        w.Line($"public const int Id = {m.TypeId}; // FNV-1a of \"{EscapeString(m.IdName)}\"");
        w.Line("public int TypeId => Id;");
    }

    /// <summary>Whether a body nested too deep can be read later, and the empty instance it is read into.</summary>
    private static void EmitDeferral(CodeWriter w, TypeModel m)
    {
        string t = m.TypeName;
        w.Line($"public bool Nests => {(m.Nests ? "true" : "false")};");
        if (!m.Deferrable)
        {
            w.Line("public bool Deferrable => false;");
            w.Line($"public {t} Create() => default;");
            return;
        }

        var c = m.Construction;
        string create = (c.Factory.Length != 0 ? c.Factory : c.Creator) + "()";
        if (m.Pooled)
            create = t + ".RentFromNinoPool() ?? " + create;
        w.Line("public bool Deferrable => true;");
        w.Line($"public {t} Create() => {create};");
    }

    /// <summary>Serialize/Deserialize forwarding to the given calls, behind a reference header when tracked.</summary>
    private static void EmitEntryPoints(CodeWriter w, TypeModel m, string write, string read)
    {
        string t = m.TypeName;
        if (!m.TrackReferences)
        {
            w.Line($"public void Serialize({t} value, ref {Core}Writer writer) => {write};");
            w.Line();
            w.Line($"public void Deserialize(ref {t} value, ref {Core}Reader reader) => {read};");
            return;
        }

        w.Block($"public void Serialize({t} value, ref {Core}Writer writer)", () =>
        {
            w.Line("if (writer.WriteReference(value))");
            w.Indented(() => w.Line($"{write};"));
        });
        w.Line();
        w.Block($"public void Deserialize(ref {t} value, ref {Core}Reader reader)", () =>
        {
            w.Line("if (!reader.ReadReference(ref value, out int __index))");
            w.Indented(() => w.Line("return;"));
            w.Line($"{read};");
            w.Line("reader.EndReference(__index, value);");
        });
    }

    /// <summary>
    /// Type id (0 = null) and body. A class's own type is checked first; subtypes go through the generated dispatch
    /// (<see cref="DispatchEmitter"/>).
    /// </summary>
    private static void EmitDispatchingEntryPoints(CodeWriter w, TypeModel m, bool ownId)
    {
        string t = m.TypeName;
        string self = m.FormatterName;
        // The root's dispatch covers every subtype of this class. Writing needs nothing more (its checks are exact);
        // reading checks that the type the data named is one of this class.
        bool root = m.IsDispatchRoot;
        string write = root ? "__WriteSubtype(value, ref writer)" : $"{m.DispatchRootFormatter}.__WriteSubtype(value, ref writer)";
        string read = root
            ? "__ReadSubtype(id, ref value, ref reader);"
            : $"{m.DispatchRootFormatter}.__ReadSubtype(id, ref {Core}NinoObject.AsBaseSlot<{t}, {m.DispatchRoot}>(ref value), ref reader); {Core}NinoObject.EnsureSubtype<{t}>(value);";
        w.Line($"public void Serialize({t} value, ref {Core}Writer writer)");
        w.Indented(() => w.Line(ownId
            ? $"{{ if (!{Core}NinoObject.TryWriteOwn<{t}, {self}>(value, ref writer)) {write}; }}"
            : $"{{ if (value == null) writer.UnsafeWrite({NinoWire.NullTypeId}); else {write}; }}"));
        w.Line();
        w.Line($"public void Deserialize(ref {t} value, ref {Core}Reader reader)");
        w.Indented(() => w.Line(ownId
            ? $"{{ int id = reader.UnsafeRead<int>(); if (!{Core}NinoObject.TryReadOwn<{t}, {self}>(id, ref value, ref reader)) {{ {read} }} }}"
            : $"{{ int id = reader.UnsafeRead<int>(); {read} }}"));
    }

    private static void EmitRegister(CodeWriter w, TypeModel m)
    {
        if (m.IsGeneric)
            return;
        w.Block("internal static void __Register()", () =>
        {
            w.Line($"{Core}NinoFormatterCache<{m.TypeName}>.{(m.FixedSize ? "TryRegisterFixed" : "TryRegister")}<{m.FormatterName}>();");
            if (m.Kind != FormatterKind.Polymorphic)
                w.Line($"{Core}NinoPolymorphic.{(m.TrackReferences ? "RegisterTracked" : "Register")}<{m.TypeName}, {m.FormatterName}>(Id);");
        });
    }
}
