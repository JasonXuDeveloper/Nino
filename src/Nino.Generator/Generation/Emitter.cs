using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace Nino.Generator.Generation;

/// <summary>Emits the source of one type's formatter, and the assembly registry.</summary>
internal static class Emitter
{
    private const string Core = "global::Nino.Core.";
    private const string Inline =
        "[global::System.Runtime.CompilerServices.MethodImpl(global::System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]";

    private const string Header = "// <auto-generated/>\n#nullable disable\n#pragma warning disable\n\n";

    private static string Id(string name) =>
        SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None ? "@" + name : name;

    public static string EmitType(TypeModel model)
    {
        var body = new StringBuilder(4096);
        EmitFormatter(body, model);

        var sb = new StringBuilder(body.Length + 1024);
        sb.Append(Header);
        sb.AppendLine("namespace NinoGen");
        sb.AppendLine("{");
        sb.Append(ShortenNames(body, model));
        sb.AppendLine("}");
        if (model.AccessorDeclarations.Length > 0)
            EmitPartialAccessor(sb, model);
        return sb.ToString();
    }

    /// <summary>
    /// Replaces repeated formatter type names with file-local <c>using</c> aliases. Member formatter names are
    /// long and repeated (serialize, deserialize, registration), so this keeps generated files small and fast to
    /// parse.
    /// </summary>
    private static string ShortenNames(StringBuilder body, TypeModel m)
    {
        var typeParameters = m.TypeParameters.Length == 0
            ? new string[0]
            : m.TypeParameters.Trim('<', '>').Split(',').Select(p => p.Trim()).ToArray();
        var aliases = new StringBuilder();
        if (body.ToString().Contains(Inline))
        {
            aliases.AppendLine("    using __NinoInline = global::System.Runtime.CompilerServices.MethodImplAttribute;");
            aliases.AppendLine("    using __NinoInlineOptions = global::System.Runtime.CompilerServices.MethodImplOptions;");
            body.Replace(Inline, "[__NinoInline(__NinoInlineOptions.AggressiveInlining)]");
        }

        int index = 0;
        foreach (var formatter in m.Members.Select(x => x.Formatter)
                     .Where(f => f.Length > 48 && !MentionsAny(f, typeParameters))
                     .Distinct()
                     .OrderByDescending(f => f.Length))
        {
            string alias = "__NinoF" + index++;
            aliases.AppendLine($"    using {alias} = {formatter};");
            body.Replace($"default({formatter})", $"default({alias})");
        }

        return aliases.AppendLine().Append(body).ToString();
    }

    private static bool MentionsAny(string text, string[] identifiers)
    {
        foreach (var id in identifiers)
        {
            int i = 0;
            while ((i = text.IndexOf(id, i, System.StringComparison.Ordinal)) >= 0)
            {
                bool start = i == 0 || !IsIdentifierChar(text[i - 1]);
                bool end = i + id.Length == text.Length || !IsIdentifierChar(text[i + id.Length]);
                if (start && end)
                    return true;
                i += id.Length;
            }
        }

        return false;
    }

    private static bool IsIdentifierChar(char c) => char.IsLetterOrDigit(c) || c == '_' || c == '@';

    private static void EmitFormatter(StringBuilder sb, TypeModel m)
    {
        string t = m.TypeName;
        string f = m.FormatterName + m.TypeParameters;
        string iface = m.Kind == FormatterKind.Polymorphic
            ? $"{Core}INinoFormatter<{t}>"
            : $"{Core}INinoBodyFormatter<{t}>";

        sb.AppendLine($"    /// <summary>Nino formatter for <c>{EscapeXml(t.Replace("global::", ""))}</c>.</summary>");
        sb.AppendLine("    [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
        if (m.RawStruct)
            iface += $", {Core}INinoRawFormatter";
        sb.AppendLine($"    internal struct {f} : {iface}{m.Constraints}");
        sb.AppendLine("    {");

        // The forwarders and TypeId are a few bytes of IL, which every runtime inlines without being told to;
        // MethodImpl attributes on them only cost compile time.
        if (m.Kind == FormatterKind.Polymorphic)
        {
            EmitEntryPoints(sb, m, $"default({Core}PolymorphicFormatter<{t}>).Serialize(value, ref writer)",
                $"default({Core}PolymorphicFormatter<{t}>).Deserialize(ref value, ref reader)");
            sb.AppendLine();
            if (m.EmitMembers)
            {
                EmitMembersMethods(sb, m);
                sb.AppendLine();
            }

            EmitRegister(sb, m);
            sb.AppendLine("    }");
            return;
        }

        // type id
        if (m.IsGeneric)
        {
            sb.AppendLine($"        private static readonly int s_typeId = {Core}NinoTypeId.Of(typeof({t}));");
            sb.AppendLine();
            sb.AppendLine("        public int TypeId");
            sb.AppendLine("        {");
            sb.AppendLine("            get => s_typeId;");
            sb.AppendLine("        }");
        }
        else
        {
            sb.AppendLine($"        /// <summary>FNV-1a of \"{EscapeXml(m.IdName)}\".</summary>");
            sb.AppendLine($"        public const int Id = {m.TypeId};");
            sb.AppendLine();
            sb.AppendLine("        public int TypeId");
            sb.AppendLine("        {");
            sb.AppendLine("            get => Id;");
            sb.AppendLine("        }");
        }

        sb.AppendLine();
        string self = m.FormatterName + m.TypeParameters;
        switch (m.Kind)
        {
            case FormatterKind.Struct:
                sb.AppendLine($"        public void Serialize({t} value, ref {Core}Writer writer) => WriteBody(value, ref writer);");
                sb.AppendLine();
                sb.AppendLine($"        public void Deserialize(ref {t} value, ref {Core}Reader reader) => ReadBody(ref value, ref reader);");
                break;
            case FormatterKind.SealedClass when m.TrackReferences:
                // The reference header already says the object is not null.
                EmitEntryPoints(sb, m, "WriteBody(value, ref writer)", "ReadBody(ref value, ref reader)");
                break;
            case FormatterKind.SealedClass:
                EmitEntryPoints(sb, m, $"{Core}NinoObject.SerializeSealed<{t}, {self}>(value, ref writer)",
                    $"{Core}NinoObject.DeserializeSealed<{t}, {self}>(ref value, ref reader)");
                break;
            default:
                EmitEntryPoints(sb, m, $"{Core}NinoObject.Serialize<{t}, {self}>(value, ref writer)",
                    $"{Core}NinoObject.Deserialize<{t}, {self}>(ref value, ref reader)");
                break;
        }

        sb.AppendLine();
        if (m.RawStruct)
        {
            sb.AppendLine("        // Unmanaged and every field serialized: the struct is written as its raw memory.");
            sb.AppendLine($"        {Inline}");
            sb.AppendLine($"        public void WriteBody({m.TypeName} value, ref {Core}Writer writer) => writer.UnsafeWrite(value);");
            sb.AppendLine();
            sb.AppendLine($"        {Inline}");
            sb.AppendLine($"        public void ReadBody(ref {m.TypeName} value, ref {Core}Reader reader) => value = reader.UnsafeRead<{m.TypeName}>();");
        }
        else
        {
            EmitWriteBody(sb, m);
            sb.AppendLine();
            EmitReadBody(sb, m);
        }
        EmitUnsafeAccessors(sb, m);
        if (!m.IsGeneric)
        {
            sb.AppendLine();
            EmitRegister(sb, m);
        }

        sb.AppendLine("    }");
    }

    /// <summary>Serialize/Deserialize forwarding to the given calls, behind a reference header when tracked.</summary>
    private static void EmitEntryPoints(StringBuilder sb, TypeModel m, string write, string read)
    {
        string t = m.TypeName;
        if (!m.TrackReferences)
        {
            sb.AppendLine($"        public void Serialize({t} value, ref {Core}Writer writer) => {write};");
            sb.AppendLine();
            sb.AppendLine($"        public void Deserialize(ref {t} value, ref {Core}Reader reader) => {read};");
            return;
        }

        sb.AppendLine($"        public void Serialize({t} value, ref {Core}Writer writer)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (writer.WriteReference(value))");
        sb.AppendLine($"                {write};");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine($"        public void Deserialize(ref {t} value, ref {Core}Reader reader)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (!reader.ReadReference(ref value, out int __index))");
        sb.AppendLine("                return;");
        sb.AppendLine($"            {read};");
        sb.AppendLine("            reader.EndReference(__index, value);");
        sb.AppendLine("        }");
    }

    private static void EmitRegister(StringBuilder sb, TypeModel m)
    {
        if (m.IsGeneric)
            return;
        string t = m.TypeName;
        string f = m.FormatterName;
        sb.AppendLine("        internal static void __Register()");
        sb.AppendLine("        {");
        sb.AppendLine($"            {Core}NinoFormatterCache<{t}>.TryRegister<{f}>();");
        if (m.Kind != FormatterKind.Polymorphic)
        {
            sb.AppendLine($"            {Core}NinoPolymorphic.Register<{t}, {f}>(Id);");
        }
        sb.AppendLine("        }");
    }

    // ----- member access -------------------------------------------------------------------------------------

    private static string Accessor(TypeModel m) => $"{m.TypeName}.{ModelBuilder.AccessorClass(m)}";

    private static bool IsReadonlyField(MemberModel member) => !member.IsProperty && member.ConstructionOnly;

    private static string Instance(MemberModel member, string v) => member.DeclaringTypeIsValueType ? "ref " + v : v;

    /// <summary>Expression reading the member of <paramref name="v"/>.</summary>
    private static string Get(TypeModel m, MemberModel member, string v)
    {
        switch (member.Access)
        {
            case MemberAccess.Direct:
                return $"{v}.{Id(member.Name)}";
            case MemberAccess.UnsafeAccessor:
                return member.IsProperty
                    ? $"__G_{member.Name}({Instance(member, v)})"
                    : $"__F_{member.Name}({Instance(member, v)})";
            default:
                return member.IsProperty || IsReadonlyField(member)
                    ? $"{Accessor(m)}.G_{member.Name}({Instance(member, v)})"
                    : $"{Accessor(m)}.F_{member.Name}({Instance(member, v)})";
        }
    }

    /// <summary>Assignable reference to a field of <paramref name="v"/>, or null for properties.</summary>
    private static string? Ref(TypeModel m, MemberModel member, string v)
    {
        if (member.IsProperty)
            return null;
        return member.Access switch
        {
            MemberAccess.Direct => $"{v}.{Id(member.Name)}",
            MemberAccess.UnsafeAccessor => $"__F_{member.Name}({Instance(member, v)})",
            _ => $"{Accessor(m)}.F_{member.Name}({Instance(member, v)})",
        };
    }

    /// <summary>Statement assigning <paramref name="expr"/> to the member of <paramref name="v"/>.</summary>
    private static string Set(TypeModel m, MemberModel member, string v, string expr)
    {
        if (!member.IsProperty)
            return $"{Ref(m, member, v)} = {expr};";
        return member.Access switch
        {
            MemberAccess.Direct => $"{v}.{Id(member.Name)} = {expr};",
            MemberAccess.UnsafeAccessor => $"__S_{member.Name}({Instance(member, v)}, {expr});",
            _ => $"{Accessor(m)}.S_{member.Name}({Instance(member, v)}, {expr});",
        };
    }

    // ----- body ----------------------------------------------------------------------------------------------

    /// <summary>Splits members into runs of raw unmanaged members (written as one block) and single members.</summary>
    private static List<List<MemberModel>> Groups(IEnumerable<MemberModel> members)
    {
        var groups = new List<List<MemberModel>>();
        List<MemberModel>? run = null;
        foreach (var member in members)
        {
            if (member.RawSize.Length != 0)
            {
                if (run == null)
                {
                    run = new List<MemberModel>();
                    groups.Add(run);
                }

                run.Add(member);
            }
            else
            {
                run = null;
                groups.Add(new List<MemberModel> { member });
            }
        }

        return groups;
    }

    private static List<string> Offsets(List<MemberModel> run, out string total)
    {
        var offsets = new List<string>();
        int constant = 0;
        var symbolic = new List<string>();
        foreach (var member in run)
        {
            offsets.Add(Sum(constant, symbolic));
            if (int.TryParse(member.RawSize, out int size))
                constant += size;
            else
                symbolic.Add(member.RawSize);
        }

        total = Sum(constant, symbolic);
        return offsets;
    }

    private static string Sum(int constant, List<string> symbolic)
    {
        if (symbolic.Count == 0)
            return constant.ToString();
        var parts = new List<string>(symbolic);
        if (constant != 0)
            parts.Insert(0, constant.ToString());
        return string.Join(" + ", parts);
    }

    /// <summary>Whether the body is prefixed with its length (version tolerant or keyed).</summary>
    private static bool Sliced(TypeModel m) => m.VersionTolerant || m.Keyed;

    private static void EmitWriteBody(StringBuilder sb, TypeModel m)
    {
        sb.AppendLine($"        public void WriteBody({m.TypeName} value, ref {Core}Writer writer)");
        sb.AppendLine("        {");
        if (Sliced(m))
            sb.AppendLine("            int __length = writer.ReserveInt32();");
        if (m.CollectionFormatter.Length != 0)
            sb.AppendLine($"            default({m.CollectionFormatter}).Serialize(value, ref writer);");
        if (m.EmitMembers)
            sb.AppendLine("            WriteMembers(value, ref writer);");
        else
            EmitMemberWrites(sb, m);
        if (Sliced(m))
            sb.AppendLine("            writer.PatchLength(__length);");
        sb.AppendLine("        }");

        if (m.EmitMembers)
        {
            sb.AppendLine();
            EmitMembersMethods(sb, m);
        }
    }

    /// <summary>Static member (de)serializers that derived types call instead of repeating these members.</summary>
    private static void EmitMembersMethods(StringBuilder sb, TypeModel m)
    {
        // Inlined so the writer/reader state stays in registers across levels, as if the members were written inline.
        sb.AppendLine($"        {Inline}");
        sb.AppendLine($"        internal static void WriteMembers({m.TypeName} value, ref {Core}Writer writer)");
        sb.AppendLine("        {");
        EmitMemberWrites(sb, m);
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        /// <summary>Reads the members into an existing instance; false when a tolerant body ended early.</summary>");
        sb.AppendLine($"        {Inline}");
        sb.AppendLine($"        internal static bool ReadMembers({m.TypeName} value, ref {Core}Reader reader)");
        sb.AppendLine("        {");
        EmitMemberReads(sb, m, "reader", inPlace: true, onEnd: "return false;");
        sb.AppendLine("            return true;");
        sb.AppendLine("        }");
    }

    private static IEnumerable<MemberModel> OwnMembers(TypeModel m) =>
        m.BaseFormatter.Length == 0 ? m.Members : m.Members.Skip(m.BaseMemberCount);

    private static void EmitMemberWrites(StringBuilder sb, TypeModel m)
    {
        if (m.BaseFormatter.Length != 0)
            sb.AppendLine($"            {m.BaseFormatter}.WriteMembers(value, ref writer);");

        if (m.Keyed)
        {
            EmitKeyedWrites(sb, m);
            return;
        }

        int block = 0;
        foreach (var group in Groups(OwnMembers(m)))
        {
            var first = group[0];
            if (first.RawSize.Length == 0)
            {
                sb.AppendLine("            " + (DirectWrite(first, Get(m, first, "value")) ??
                                             $"default({first.Formatter}).Serialize({Get(m, first, "value")}, ref writer);"));
                continue;
            }

            if (group.Count == 1)
            {
                sb.AppendLine($"            writer.UnsafeWrite<{first.TypeName}>({Get(m, first, "value")});");
                continue;
            }

            var offsets = Offsets(group, out var total);
            string p = "__p" + block++;
            sb.AppendLine($"            ref byte {p} = ref writer.Reserve({total});");
            for (int i = 0; i < group.Count; i++)
                sb.AppendLine($"            {Core}NinoUnsafe.Write<{group[i].TypeName}>(ref {p}, {offsets[i]}, {Get(m, group[i], "value")});");
        }
    }

    private static void EmitReadBody(StringBuilder sb, TypeModel m)
    {
        sb.AppendLine($"        public void ReadBody(ref {m.TypeName} value, ref {Core}Reader reader)");
        sb.AppendLine("        {");
        string r = "reader";
        if (Sliced(m))
        {
            sb.AppendLine("            var __reader = reader.ReadSlice();");
            r = "__reader";
        }

        var c = m.Construction;
        bool isClass = m.Kind != FormatterKind.Struct;

        if (!c.Recreate)
        {
            if (isClass)
            {
                string create = c.RefFactory.Length != 0 ? c.RefFactory + "()" : c.Creator + "()";
                sb.AppendLine("            if (value == null)");
                sb.AppendLine($"                value = {create};");
                if (m.TrackReferences)
                    sb.AppendLine("            reader.SetReference(value);");
            }

            if (m.CollectionFormatter.Length != 0)
                sb.AppendLine($"            default({m.CollectionFormatter}).Deserialize(ref value, ref {r});");

            if (m.EmitMembers)
            {
                sb.AppendLine($"            ReadMembers(value, ref {r});");
            }
            else
            {
                EmitMemberReads(sb, m, r, inPlace: true, onEnd: "goto __end;");
                if (m.VersionTolerant && !m.Keyed)
                    sb.AppendLine("            __end: ;");
            }

            if (Sliced(m))
                sb.AppendLine("            reader.EndSlice(in __reader);");

            sb.AppendLine("        }");
            return;
        }

        foreach (var member in m.Members)
            sb.AppendLine($"            {member.TypeName} {Local(member)} = default;");
        EmitMemberReads(sb, m, r, inPlace: false, onEnd: "goto __end;");
        if (m.VersionTolerant && !m.Keyed)
            sb.AppendLine("            __end:");
        if (Sliced(m))
            sb.AppendLine("            reader.EndSlice(in __reader);");

        if (c.Creator.Length == 0)
        {
            sb.AppendLine($"            throw new global::System.NotSupportedException(\"Nino: cannot construct {EscapeString(m.TypeName)}\");");
            sb.AppendLine("        }");
            return;
        }

        if (isClass)
            sb.AppendLine("            var __old = value;");

        var args = new HashSet<string>(c.Arguments);
        var initializers = m.Members.Where(x =>
            !args.Contains(x.Name) && !x.Unassignable && x.Access == MemberAccess.Direct).ToList();
        string call = c.Creator + "(" + string.Join(", ", c.Arguments.Select(a => Local(m.Members.First(x => x.Name == a)))) + ")";
        if (initializers.Count == 0)
        {
            sb.AppendLine($"            value = {call};");
        }
        else
        {
            sb.AppendLine($"            value = {call}");
            sb.AppendLine("            {");
            foreach (var member in initializers)
                sb.AppendLine($"                {Id(member.Name)} = {Local(member)},");
            sb.AppendLine("            };");
        }

        foreach (var member in m.Members.Where(x =>
                     !args.Contains(x.Name) && !x.Unassignable && x.Access != MemberAccess.Direct))
            sb.AppendLine("            " + Set(m, member, "value", Local(member)));

        if (isClass)
        {
            sb.AppendLine("            if (__old != null)");
            sb.AppendLine($"                {Core}NinoRecycler<{m.TypeName}>.Recycle(__old);");
        }

        sb.AppendLine("        }");
    }

    private static string Local(MemberModel member) => "__v_" + member.Name;

    private static void EmitMemberReads(StringBuilder sb, TypeModel m, string r, bool inPlace, string onEnd)
    {
        // Base members through the base formatter (in place only: recreated types read everything into locals).
        var members = inPlace ? OwnMembers(m) : m.Members;
        if (inPlace && m.BaseFormatter.Length != 0)
        {
            sb.AppendLine(m.VersionTolerant
                ? $"            if (!{m.BaseFormatter}.ReadMembers(value, ref {r})) {onEnd}"
                : $"            {m.BaseFormatter}.ReadMembers(value, ref {r});");
        }

        if (m.Keyed)
        {
            EmitKeyedReads(sb, m, members, r, inPlace);
            return;
        }

        if (m.VersionTolerant)
        {
            // Tolerant bodies may end early (data written by an older version): check before every member.
            foreach (var member in members)
            {
                sb.AppendLine($"            if ({r}.Eof) {onEnd}");
                if (member.RawSize.Length != 0)
                {
                    string read = $"{r}.UnsafeRead<{member.TypeName}>()";
                    sb.AppendLine("            " + (inPlace ? Set(m, member, "value", read) : $"{Local(member)} = {read};"));
                }
                else
                {
                    EmitFormatterRead(sb, m, member, r, inPlace);
                }
            }

            return;
        }

        int block = 0;
        foreach (var group in Groups(members))
        {
            var first = group[0];
            if (first.RawSize.Length == 0)
            {
                EmitFormatterRead(sb, m, first, r, inPlace);
                continue;
            }

            if (group.Count == 1)
            {
                string read = $"{r}.UnsafeRead<{first.TypeName}>()";
                sb.AppendLine("            " + (inPlace ? Set(m, first, "value", read) : $"{Local(first)} = {read};"));
                continue;
            }

            var offsets = Offsets(group, out var total);
            string p = "__p" + block++;
            sb.AppendLine($"            ref byte {p} = ref {r}.ReadBlock({total});");
            for (int i = 0; i < group.Count; i++)
            {
                string read = $"{Core}NinoUnsafe.Read<{group[i].TypeName}>(ref {p}, {offsets[i]})";
                sb.AppendLine("            " + (inPlace ? Set(m, group[i], "value", read) : $"{Local(group[i])} = {read};"));
            }
        }
    }

    private static int Key(MemberModel member) => TypeNames.ComputeId(member.Name);

    /// <summary>(key, length) as the int64 a reader sees, for raw members of constant size; else null.</summary>
    private static string? KeyHeader(MemberModel member)
    {
        if (member.RawSize.Length == 0 || !int.TryParse(member.RawSize, out int size))
            return null;
        uint key = unchecked((uint)Key(member));
        long le = (long)size << 32 | key;
        long be = (long)key << 32 | (uint)size;
        return le == be ? $"{le}L" : $"(global::System.BitConverter.IsLittleEndian ? {le}L : {be}L)";
    }

    /// <summary>Each member as (key, length, value); consecutive raw members share one reservation.</summary>
    private static void EmitKeyedWrites(StringBuilder sb, TypeModel m)
    {
        int block = 0, index = 0;
        foreach (var group in Groups(m.Members))
        {
            var first = group[0];
            if (first.RawSize.Length == 0)
            {
                string l = "__l" + index++;
                sb.AppendLine($"            writer.UnsafeWrite<int>({Key(first)});");
                sb.AppendLine($"            int {l} = writer.ReserveInt32();");
                sb.AppendLine("            " + (DirectWrite(first, Get(m, first, "value")) ??
                                             $"default({first.Formatter}).Serialize({Get(m, first, "value")}, ref writer);"));
                sb.AppendLine($"            writer.PatchLength({l});");
                continue;
            }

            int constant = 0;
            var symbolic = new List<string>();
            var lines = new List<string>();
            string p = "__p" + block++;
            foreach (var member in group)
            {
                lines.Add($"            {Core}NinoUnsafe.Write<int>(ref {p}, {Sum(constant, symbolic)}, {Key(member)});");
                lines.Add($"            {Core}NinoUnsafe.Write<int>(ref {p}, {Sum(constant + 4, symbolic)}, {member.RawSize});");
                lines.Add($"            {Core}NinoUnsafe.Write<{member.TypeName}>(ref {p}, {Sum(constant + 8, symbolic)}, {Get(m, member, "value")});");
                constant += 8;
                if (int.TryParse(member.RawSize, out int size))
                    constant += size;
                else
                    symbolic.Add(member.RawSize);
            }

            sb.AppendLine($"            ref byte {p} = ref writer.Reserve({Sum(constant, symbolic)});");
            foreach (var line in lines)
                sb.AppendLine(line);
        }
    }

    /// <summary>
    /// Reads members written in declaration order straight through (raw members check key and length with one
    /// 8-byte compare); at the first unexpected key, falls back to a loop that dispatches any key.
    /// </summary>
    private static void EmitKeyedReads(StringBuilder sb, TypeModel m, IEnumerable<MemberModel> members, string r,
        bool inPlace)
    {
        var list = members.ToList();
        foreach (var member in list)
        {
            var header = KeyHeader(member);
            if (header != null)
            {
                string read = $"{r}.UnsafeRead<{member.TypeName}>()";
                sb.AppendLine($"            if (!{r}.TryReadInt64({header})) goto __keyed;");
                sb.AppendLine("            " + (inPlace ? Set(m, member, "value", read) : $"{Local(member)} = {read};"));
                continue;
            }

            sb.AppendLine($"            if (!{r}.TryReadInt32({Key(member)})) goto __keyed;");
            sb.AppendLine("            {");
            sb.AppendLine($"                var __m = {r}.ReadSlice();");
            EmitKeyedMemberRead(sb, m, member, inPlace, "    ");
            sb.AppendLine($"                {r}.EndSlice(in __m);");
            sb.AppendLine("            }");
        }

        // Unknown members appended by a newer version, or members in another order.
        if (list.Count != 0)
            sb.AppendLine("            __keyed:");
        sb.AppendLine($"            while (!{r}.Eof)");
        sb.AppendLine("            {");
        sb.AppendLine($"                int __key = {r}.UnsafeRead<int>();");
        sb.AppendLine($"                var __m = {r}.ReadSlice();");
        if (list.Count != 0)
        {
            sb.AppendLine("                switch (__key)");
            sb.AppendLine("                {");
            foreach (var member in list)
            {
                sb.AppendLine($"                    case {Key(member)}:");
                sb.AppendLine("                    {");
                EmitKeyedMemberRead(sb, m, member, inPlace, "            ");
                if (member.RawSize.Length == 0)
                    sb.AppendLine($"                        {r}.EndSlice(in __m);");
                sb.AppendLine("                        break;");
                sb.AppendLine("                    }");
            }

            sb.AppendLine("                }");
        }

        sb.AppendLine("            }");
    }

    private static void EmitKeyedMemberRead(StringBuilder sb, TypeModel m, MemberModel member, bool inPlace,
        string indent)
    {
        var body = new StringBuilder();
        if (member.RawSize.Length != 0)
        {
            string read = $"__m.UnsafeRead<{member.TypeName}>()";
            body.AppendLine("            " + (inPlace ? Set(m, member, "value", read) : $"{Local(member)} = {read};"));
        }
        else
        {
            EmitFormatterRead(body, m, member, "__m", inPlace);
        }

        foreach (var line in body.ToString().Split(new[] { '\n' }, System.StringSplitOptions.RemoveEmptyEntries))
            sb.AppendLine(indent + line.TrimEnd('\r'));
    }

    /// <summary>
    /// For formatters that never reuse the current value (strings), the read expression that replaces the
    /// formatter call. Avoids a property getter call and keeps the generated code short.
    /// </summary>
    private static string? DirectRead(MemberModel member, string r) => member.Formatter switch
    {
        Core + "StringFormatter" => $"{r}.ReadString()",
        Core + "Utf8StringFormatter" => $"{r}.ReadUtf8()",
        _ => null,
    };

    private static string? DirectWrite(MemberModel member, string value) => member.Formatter switch
    {
        Core + "StringFormatter" => $"writer.Write({value});",
        Core + "Utf8StringFormatter" => $"writer.WriteUtf8({value});",
        _ => null,
    };

    private static void EmitFormatterRead(StringBuilder sb, TypeModel m, MemberModel member, string r, bool inPlace)
    {
        var direct = DirectRead(member, r);
        if (direct != null)
        {
            sb.AppendLine("            " + (inPlace ? Set(m, member, "value", direct) : $"{Local(member)} = {direct};"));
            return;
        }

        if (!inPlace)
        {
            sb.AppendLine($"            default({member.Formatter}).Deserialize(ref {Local(member)}, ref {r});");
            return;
        }

        var reference = Ref(m, member, "value");
        if (reference != null)
        {
            sb.AppendLine($"            default({member.Formatter}).Deserialize(ref {reference}, ref {r});");
            return;
        }

        // Properties: read through a local so the existing instance is reused, then assign it back.
        sb.AppendLine("            {");
        sb.AppendLine($"                var __t = {Get(m, member, "value")};");
        sb.AppendLine($"                default({member.Formatter}).Deserialize(ref __t, ref {r});");
        sb.AppendLine("                " + Set(m, member, "value", "__t"));
        sb.AppendLine("            }");
    }

    // ----- private member access -----------------------------------------------------------------------------

    private static void EmitUnsafeAccessors(StringBuilder sb, TypeModel m)
    {
        const string attr = "global::System.Runtime.CompilerServices.UnsafeAccessor";
        const string kind = "global::System.Runtime.CompilerServices.UnsafeAccessorKind";
        foreach (var member in m.Members.Where(x => x.Access == MemberAccess.UnsafeAccessor))
        {
            string self = (member.DeclaringTypeIsValueType ? "ref " : "") + member.DeclaringType + " @this";
            sb.AppendLine();
            if (member.IsProperty)
            {
                sb.AppendLine($"        [{attr}({kind}.Method, Name = \"get_{member.Name}\")]");
                sb.AppendLine($"        private static extern {member.TypeName} __G_{member.Name}({self});");
                sb.AppendLine($"        [{attr}({kind}.Method, Name = \"set_{member.Name}\")]");
                sb.AppendLine($"        private static extern void __S_{member.Name}({self}, {member.TypeName} value);");
            }
            else
            {
                sb.AppendLine($"        [{attr}({kind}.Field, Name = \"{member.Name}\")]");
                sb.AppendLine($"        private static extern ref {member.TypeName} __F_{member.Name}({self});");
            }
        }
    }

    private static void EmitPartialAccessor(StringBuilder sb, TypeModel m)
    {
        var members = m.Members.Where(x => x.Access == MemberAccess.Partial).ToList();
        sb.AppendLine();
        bool hasNamespace = m.AccessorNamespace.Length != 0;
        string indent = "";
        if (hasNamespace)
        {
            sb.AppendLine($"namespace {m.AccessorNamespace}");
            sb.AppendLine("{");
            indent = "    ";
        }

        foreach (var declaration in m.AccessorDeclarations)
        {
            sb.AppendLine($"{indent}{declaration}");
            sb.AppendLine($"{indent}{{");
            indent += "    ";
        }

        string t = m.TypeName;
        sb.AppendLine($"{indent}[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
        sb.AppendLine($"{indent}internal static class {ModelBuilder.AccessorClass(m)}");
        sb.AppendLine($"{indent}{{");
        foreach (var member in members)
        {
            string o = (member.DeclaringTypeIsValueType ? "ref " : "") + t + " o";
            string name = Id(member.Name);
            sb.AppendLine($"{indent}    {Inline}");
            sb.AppendLine($"{indent}    internal static {member.TypeName} G_{member.Name}({o}) => o.{name};");
            if (member.IsProperty)
            {
                if (!member.ConstructionOnly)
                {
                    sb.AppendLine($"{indent}    {Inline}");
                    sb.AppendLine($"{indent}    internal static void S_{member.Name}({o}, {member.TypeName} value) => o.{name} = value;");
                }
            }
            else if (!member.ConstructionOnly)
            {
                sb.AppendLine($"{indent}    {Inline}");
                sb.AppendLine($"{indent}    internal static ref {member.TypeName} F_{member.Name}({o}) => ref o.{name};");
            }
        }

        sb.AppendLine($"{indent}}}");
        for (int i = 0; i < m.AccessorDeclarations.Length; i++)
        {
            indent = indent.Substring(4);
            sb.AppendLine($"{indent}}}");
        }

        if (hasNamespace)
            sb.AppendLine("}");
    }

    // ----- registry --------------------------------------------------------------------------------------------

    /// <summary>
    /// Emits <c>Register(int id)</c> as a switch over small bucket methods: the JIT resolves every call in a method
    /// it compiles, so one switch over every type would load every formatter on the first lookup. With buckets of
    /// about eight ids, a lookup only loads the types of its bucket.
    /// </summary>
    private static void EmitIdDispatch(StringBuilder sb, string modifiers, string prelude,
        List<KeyValuePair<int, List<string>>> cases)
    {
        int buckets = 1;
        while (buckets < 256 && buckets * 8 < cases.Count)
            buckets *= 2;

        sb.AppendLine($"        {modifiers} void Register(int id)");
        sb.AppendLine("        {");
        if (prelude.Length != 0)
            sb.AppendLine($"            {prelude}");
        if (buckets == 1)
        {
            EmitIdSwitch(sb, cases);
            sb.AppendLine("        }");
            return;
        }

        sb.AppendLine($"            switch (id & {buckets - 1})");
        sb.AppendLine("            {");
        var byBucket = cases.GroupBy(c => c.Key & (buckets - 1)).OrderBy(g => g.Key).ToList();
        foreach (var bucket in byBucket)
            sb.AppendLine($"                case {bucket.Key}: __Bucket{bucket.Key}(id); break;");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
        foreach (var bucket in byBucket)
        {
            sb.AppendLine();
            sb.AppendLine($"        private static void __Bucket{bucket.Key}(int id)");
            sb.AppendLine("        {");
            EmitIdSwitch(sb, bucket.ToList());
            sb.AppendLine("        }");
        }
    }

    private static void EmitIdSwitch(StringBuilder sb, List<KeyValuePair<int, List<string>>> cases)
    {
        if (cases.Count == 0)
            return;
        sb.AppendLine("            switch (id)");
        sb.AppendLine("            {");
        foreach (var c in cases)
        {
            sb.AppendLine($"                case {c.Key}:");
            foreach (var statement in c.Value)
                sb.AppendLine($"                    {statement}");
            sb.AppendLine("                    break;");
        }

        sb.AppendLine("            }");
    }

    public static string EmitRegistry(GeneratorOptions options, IEnumerable<RegistryEntry> entries)
    {
        string name = "NinoGenRegistry_" + new string(options.AssemblyName
            .Select(ch => char.IsLetterOrDigit(ch) ? ch : '_').ToArray());
        var sb = new StringBuilder();
        sb.Append(Header);
        sb.AppendLine($"[assembly: {Core}NinoGenerated(typeof(global::NinoGen.{name}))]");
        sb.AppendLine();
        sb.AppendLine("namespace NinoGen");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// Registers the Nino formatters generated for this assembly, lazily: a lookup that misses asks for the");
        sb.AppendLine("    /// type id it needs, so startup does not touch types that are never used.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine("    [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
        sb.AppendLine($"    internal sealed class {name} : {Core}INinoRegistry");
        sb.AppendLine("    {");
        sb.AppendLine($"        static {name}()");
        sb.AppendLine("        {");
        sb.AppendLine($"            {Core}NinoRegistry.Add(new {name}());");
        var list = entries.OrderBy(e => e.FormatterName, System.StringComparer.Ordinal).ToList();
        foreach (var entry in list.Where(e => e.OpenTypeName.Length != 0))
            sb.AppendLine($"            {Core}NinoRegistry.RegisterGeneric(typeof({entry.OpenTypeName}), typeof({entry.FormatterName}<{new string(',', entry.Arity - 1)}>));");
        sb.AppendLine("        }");
        sb.AppendLine();
        EmitIdDispatch(sb, "public", "global::NinoGen.NinoGenUsages.Register(id);",
            // Keyed by wire id (polymorphic reads) and, for [NinoFormerName] types, also by name id (by-type lookups).
            list.Where(e => e.OpenTypeName.Length == 0)
                .SelectMany(e => e.NameId == e.TypeId
                    ? new[] { (Id: e.TypeId, Entry: e) }
                    : new[] { (Id: e.TypeId, Entry: e), (Id: e.NameId, Entry: e) })
                .GroupBy(x => x.Id, x => x.Entry).OrderBy(g => g.Key)
                .Select(g => new KeyValuePair<int, List<string>>(g.Key,
                    g.Select(e => $"{e.FormatterName}.__Register();").ToList()))
                .ToList());
        sb.AppendLine();
        sb.AppendLine("        /// <summary>Runs the registration (once).</summary>");
        sb.AppendLine("        public static void Init()");
        sb.AppendLine("        {");
        sb.AppendLine("        }");
        if (options.HasModuleInitializer)
        {
            sb.AppendLine();
            sb.AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializer]");
            sb.AppendLine("        internal static void ModuleInit() => Init();");
        }

        if (options.HasUnityEngine)
        {
            sb.AppendLine();
            sb.AppendLine("        [global::UnityEngine.RuntimeInitializeOnLoadMethod(global::UnityEngine.RuntimeInitializeLoadType.SubsystemRegistration)]");
            sb.AppendLine("        private static void UnityInit() => Init();");
        }

        if (options.HasUnityEditor)
        {
            sb.AppendLine();
            sb.AppendLine("        [global::UnityEditor.InitializeOnLoadMethod]");
            sb.AppendLine("        private static void UnityEditorInit() => Init();");
        }

        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    public static string EmitUsages(IEnumerable<FormatterRegistration> usages)
    {
        var sb = new StringBuilder();
        sb.Append(Header);
        sb.AppendLine("namespace NinoGen");
        sb.AppendLine("{");
        sb.AppendLine("    internal static class NinoGenUsages");
        sb.AppendLine("    {");
        sb.AppendLine("        /// <summary>Registers the closed built-in formatters whose type has id <paramref name=\"id\"/>.</summary>");
        EmitIdDispatch(sb, "internal static", "",
            usages.GroupBy(u => u.Id).OrderBy(g => g.Key)
                .Select(g => new KeyValuePair<int, List<string>>(g.Key,
                    g.Select(u => $"{Core}NinoFormatterCache<{u.TypeName}>.TryRegister<{u.Formatter}>();").ToList()))
                .ToList());
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    public static string EmitPriorityQueueFormatter()
    {
        return Header + $$"""
            namespace NinoGen
            {
                /// <summary><c>PriorityQueue&lt;TElement, TPriority&gt;</c>: count (-1 = null), then (element, priority) pairs.</summary>
                internal struct NinoPriorityQueueFormatter<TElement, TPriority, TElementFormatter, TPriorityFormatter>
                    : {{Core}}INinoFormatter<global::System.Collections.Generic.PriorityQueue<TElement, TPriority>>
                    where TElementFormatter : struct, {{Core}}INinoFormatter<TElement>
                    where TPriorityFormatter : struct, {{Core}}INinoFormatter<TPriority>
                {
                    public void Serialize(global::System.Collections.Generic.PriorityQueue<TElement, TPriority> value, ref {{Core}}Writer writer)
                    {
                        if (value == null)
                        {
                            writer.WriteNullLength();
                            return;
                        }

                        writer.WriteLength(value.Count);
                        foreach (var (element, priority) in value.UnorderedItems)
                        {
                            default(TElementFormatter).Serialize(element, ref writer);
                            default(TPriorityFormatter).Serialize(priority, ref writer);
                        }
                    }

                    public void Deserialize(ref global::System.Collections.Generic.PriorityQueue<TElement, TPriority> value, ref {{Core}}Reader reader)
                    {
                        int length = reader.ReadLength();
                        if (length < 0)
                        {
                            {{Core}}NinoRecycler.Discard(ref value);
                            return;
                        }

                        var queue = value;
                        if (queue == null)
                        {
                            queue = new global::System.Collections.Generic.PriorityQueue<TElement, TPriority>(length);
                            value = queue;
                        }
                        else
                        {
                            if ({{Core}}NinoRecycler<TElement>.IsRegistered)
                            {
                                foreach (var (element, _) in queue.UnorderedItems)
                                    {{Core}}NinoRecycler<TElement>.Recycle(element);
                            }

                            queue.Clear();
                        }

                        for (int i = 0; i < length; i++)
                        {
                            TElement element = default;
                            TPriority priority = default;
                            default(TElementFormatter).Deserialize(ref element, ref reader);
                            default(TPriorityFormatter).Deserialize(ref priority, ref reader);
                            queue.Enqueue(element, priority);
                        }
                    }
                }
            }

            """;
    }

    public static string EmitImmutableFormatters()
    {
        return Header + $$"""
            namespace NinoGen
            {
                /// <summary><c>ImmutableArray&lt;T&gt;</c>: length (-1 = default), then the elements.</summary>
                internal struct NinoImmutableArrayFormatter<T, TFormatter> : {{Core}}INinoFormatter<global::System.Collections.Immutable.ImmutableArray<T>>
                    where TFormatter : struct, {{Core}}INinoFormatter<T>
                {
                    public void Serialize(global::System.Collections.Immutable.ImmutableArray<T> value, ref {{Core}}Writer writer)
                    {
                        if (value.IsDefault)
                        {
                            writer.WriteNullLength();
                            return;
                        }

                        writer.WriteLength(value.Length);
                        foreach (var item in value)
                            default(TFormatter).Serialize(item, ref writer);
                    }

                    public void Deserialize(ref global::System.Collections.Immutable.ImmutableArray<T> value, ref {{Core}}Reader reader)
                    {
                        int length = reader.ReadLength();
                        if (length < 0)
                        {
                            value = default;
                            return;
                        }

                        var builder = global::System.Collections.Immutable.ImmutableArray.CreateBuilder<T>(length);
                        for (int i = 0; i < length; i++)
                        {
                            T item = default;
                            default(TFormatter).Deserialize(ref item, ref reader);
                            builder.Add(item);
                        }

                        value = builder.MoveToImmutable();
                    }
                }

                /// <summary><c>ImmutableList&lt;T&gt;</c>: count (-1 = null), then the elements.</summary>
                internal struct NinoImmutableListFormatter<T, TFormatter> : {{Core}}INinoFormatter<global::System.Collections.Immutable.ImmutableList<T>>
                    where TFormatter : struct, {{Core}}INinoFormatter<T>
                {
                    public void Serialize(global::System.Collections.Immutable.ImmutableList<T> value, ref {{Core}}Writer writer)
                    {
                        if (value == null)
                        {
                            writer.WriteNullLength();
                            return;
                        }

                        writer.WriteLength(value.Count);
                        foreach (var item in value)
                            default(TFormatter).Serialize(item, ref writer);
                    }

                    public void Deserialize(ref global::System.Collections.Immutable.ImmutableList<T> value, ref {{Core}}Reader reader)
                    {
                        int length = reader.ReadLength();
                        if (length < 0)
                        {
                            value = null;
                            return;
                        }

                        var builder = global::System.Collections.Immutable.ImmutableList.CreateBuilder<T>();
                        for (int i = 0; i < length; i++)
                        {
                            T item = default;
                            default(TFormatter).Deserialize(ref item, ref reader);
                            builder.Add(item);
                        }

                        value = builder.ToImmutable();
                    }
                }
            }

            """;
    }

